        public static void BuildBatch()
        {
            int exit = 0;
            try { Build(); Debug.Log("TRUCK_RESULT: OK"); }
            catch (Exception e) { Debug.LogException(e); Debug.Log("TRUCK_RESULT: FAILED"); exit = 1; }
            if (Application.isBatchMode) EditorApplication.Exit(exit);
        }

        [MenuItem("Kamion/Setup/Rebuild TRAKT truck")]
        public static void Build()
        {
            var ext = Json.Obj(Json.Parse(File.ReadAllText(Path.Combine(EditorTools.RepoRoot, ExtManifest))));
            var inn = Json.Obj(Json.Parse(File.ReadAllText(Path.Combine(EditorTools.RepoRoot, IntManifest))));
            CopySources(ext, inn);
            ConfigureImporters();
            var sets = BuildMaterials(inn);
            BuildPrefab(ext, inn, sets);
            AssetDatabase.SaveAssets();
        }

        // ------------------------------------------------------------------ 1. sources

        static void CopySources(Dictionary<string, object> ext, Dictionary<string, object> inn)
        {
            var copies = new List<(string src, string dst)>();
            foreach (var lod in Json.Obj(ext["lods"]))
            {
                string f = Json.Str(Json.Obj(lod.Value)["file"]);
                copies.Add((f, $"{SrcExt}/{Path.GetFileName(f)}"));
            }
            foreach (var lod in Json.Obj(inn["lods"]))
            {
                string f = Json.Str(Json.Obj(lod.Value)["file"]);
                copies.Add((f, $"{SrcInt}/{Path.GetFileName(f)}"));
            }
            foreach (var t in Tiers)
            {
                foreach (var f in Directory.GetFiles(Path.Combine(EditorTools.RepoRoot, "art-source/truck/exterior/export/textures", t), "*.png"))
                    copies.Add(($"art-source/truck/exterior/export/textures/{t}/{Path.GetFileName(f)}", $"{SrcExt}/Textures/{t}/{Path.GetFileName(f)}"));
                foreach (var f in Directory.GetFiles(Path.Combine(EditorTools.RepoRoot, "art-source/truck/interior/export/textures", t), "*.png"))
                    copies.Add(($"art-source/truck/interior/export/textures/{t}/{Path.GetFileName(f)}", $"{SrcInt}/Textures/{t}/{Path.GetFileName(f)}"));
            }
            foreach (var f in Directory.GetFiles(Path.Combine(EditorTools.RepoRoot, "art-source/truck/interior/export/textures/Displays"), "*.png"))
                copies.Add(($"art-source/truck/interior/export/textures/Displays/{Path.GetFileName(f)}", $"{SrcInt}/Textures/Displays/{Path.GetFileName(f)}"));

            int copied = 0;
            foreach (var (src, dst) in copies)
            {
                string s = Path.Combine(EditorTools.RepoRoot, src);
                string d = Path.Combine(EditorTools.ProjectRoot, dst);
                if (!File.Exists(s))
                {
                    if (src.EndsWith("SM_CabInterior_LOD0.fbx", StringComparison.Ordinal))
                        throw new FileNotFoundException("Interior LOD0 is generated outside git: run Blender " +
                            "(tools/blender/truck/interior/a6_export.py -- --lods 0, see docs/reports/visual/truck-A7/README.md)", s);
                    throw new FileNotFoundException("missing source " + src, s);
                }
                var fs = new FileInfo(s);
                if (new FileInfo(s).Length < 1024 && File.ReadAllText(s).StartsWith("version https://git-lfs", StringComparison.Ordinal))
                    throw new InvalidDataException("LFS pointer, not the file (git lfs pull): " + src);
                var fd = new FileInfo(d);
                if (fd.Exists && fd.Length == fs.Length && fd.LastWriteTimeUtc >= fs.LastWriteTimeUtc) continue;
                Directory.CreateDirectory(Path.GetDirectoryName(d));
                File.Copy(s, d, true);
                copied++;
            }
            Debug.Log($"[TRUCK] sources: {copies.Count} files, {copied} copied");
            AssetDatabase.Refresh();
        }

        // ------------------------------------------------------------------ 2. importers

        static void ConfigureImporters()
        {
            foreach (var guid in AssetDatabase.FindAssets("t:Model", new[] { Root + "/Source" }))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid);
                if (!(AssetImporter.GetAtPath(p) is ModelImporter mi)) continue;
                if (ApplyModelSettings(mi)) mi.SaveAndReimport();
            }
            ConfigureTextureImporters();
        }

        /// <summary>Model importer settings of the vehicle FBX (also used by the wheel-geometry regression test,
        /// ADR 0039). Returns true when something changed (caller reimports).</summary>
        public static bool ApplyModelSettings(ModelImporter mi)
        {
            {
                bool dirty = false;
                void Set<T>(T cur, T want, Action<T> apply) { if (!EqualityComparer<T>.Default.Equals(cur, want)) { apply(want); dirty = true; } }
                Set(mi.globalScale, 1f, v => mi.globalScale = v);
                Set(mi.useFileUnits, true, v => mi.useFileUnits = v);
                Set(mi.bakeAxisConversion, false, v => mi.bakeAxisConversion = v);
                Set(mi.importCameras, false, v => mi.importCameras = v);
                Set(mi.importLights, false, v => mi.importLights = v);
                Set(mi.importVisibility, false, v => mi.importVisibility = v);
                Set(mi.importAnimation, false, v => mi.importAnimation = v);
                Set(mi.animationType, ModelImporterAnimationType.None, v => mi.animationType = v);
                Set(mi.importBlendShapes, false, v => mi.importBlendShapes = v);
                Set(mi.materialImportMode, ModelImporterMaterialImportMode.ImportStandard, v => mi.materialImportMode = v);
                Set(mi.materialLocation, ModelImporterMaterialLocation.InPrefab, v => mi.materialLocation = v);
                Set(mi.meshCompression, ModelImporterMeshCompression.Off, v => mi.meshCompression = v);
                Set(mi.isReadable, false, v => mi.isReadable = v);
                Set(mi.importNormals, ModelImporterNormals.Import, v => mi.importNormals = v);
                Set(mi.importTangents, ModelImporterTangents.CalculateMikk, v => mi.importTangents = v);
                Set(mi.generateSecondaryUV, false, v => mi.generateSecondaryUV = v);
                Set(mi.addCollider, false, v => mi.addCollider = v);
                return dirty;
            }
        }

        static void ConfigureTextureImporters()
        {
            foreach (var guid in AssetDatabase.FindAssets("t:Texture2D", new[] { Root + "/Source" }))
            {
                string p = AssetDatabase.GUIDToAssetPath(guid);
                if (!(AssetImporter.GetAtPath(p) is TextureImporter ti)) continue;
                string n = Path.GetFileNameWithoutExtension(p);
                string tier = p.Contains("/High/") ? "High" : p.Contains("/Medium/") ? "Medium" : p.Contains("/Low/") ? "Low" : "High";
                bool normal = n.EndsWith("_N", StringComparison.Ordinal) || n.EndsWith("_Normal", StringComparison.Ordinal);
                bool srgb = n.EndsWith("_C", StringComparison.Ordinal) || n.Contains("_BaseMap") || n.Contains("Decal") || n.StartsWith("T_Display", StringComparison.Ordinal);
                bool high = tier == "High";
                // manifest tiers.texture_compression: C 6x6 (High) / 8x8, N 5x5 (High) / 6x6, M 8x8, Decal 6x6;
                // interior: Normal 5x5 / 6x6, Detail 6x6 / 8x8, AO 6x6 / 8x8, Decal 6x6.
                TextureImporterFormat fmt =
                    normal ? (high ? TextureImporterFormat.ASTC_5x5 : TextureImporterFormat.ASTC_6x6)
                    : n.Contains("Decal") || n.StartsWith("T_Display", StringComparison.Ordinal) ? TextureImporterFormat.ASTC_6x6
                    : n.EndsWith("_M", StringComparison.Ordinal) || n.Contains("MaskMap") ? TextureImporterFormat.ASTC_8x8
                    : high ? TextureImporterFormat.ASTC_6x6 : TextureImporterFormat.ASTC_8x8;
                // B2.1: High atlases are exported at 4096 (owner priority: quality); keep the source size up to 4096.
                ti.GetSourceTextureWidthAndHeight(out int srcW, out int srcH);
                int maxSize = Mathf.Clamp(Mathf.NextPowerOfTwo(Mathf.Max(srcW, srcH)), 32, high ? 4096 : 2048);
                bool dirty = false;
                if (ti.textureType != (normal ? TextureImporterType.NormalMap : TextureImporterType.Default)) { ti.textureType = normal ? TextureImporterType.NormalMap : TextureImporterType.Default; dirty = true; }
                if (!normal && ti.sRGBTexture != srgb) { ti.sRGBTexture = srgb; dirty = true; }
                if (!ti.mipmapEnabled) { ti.mipmapEnabled = true; dirty = true; }
                if (ti.anisoLevel != 2) { ti.anisoLevel = 2; dirty = true; }
                if (ti.maxTextureSize != maxSize) { ti.maxTextureSize = maxSize; dirty = true; }
                if (ti.alphaSource != TextureImporterAlphaSource.FromInput) { ti.alphaSource = TextureImporterAlphaSource.FromInput; dirty = true; }
                if (ti.alphaIsTransparency) { ti.alphaIsTransparency = false; dirty = true; }
                var a = ti.GetPlatformTextureSettings("Android");
                if (!a.overridden || a.format != fmt || a.maxTextureSize != maxSize)
                {
                    a.overridden = true; a.format = fmt; a.maxTextureSize = maxSize; a.compressionQuality = 50;
                    ti.SetPlatformTextureSettings(a);
                    dirty = true;
                }
                if (dirty) ti.SaveAndReimport();
            }
        }

        // ------------------------------------------------------------------ 3. materials

        static T Tex<T>(string path) where T : UnityEngine.Object
        {
            var t = AssetDatabase.LoadAssetAtPath<T>(path);
            if (t == null) throw new FileNotFoundException("texture not imported: " + path);
            return t;
        }

        static Material Mat(string dir, string name, Shader shader)
        {
            string p = $"{dir}/{name}.mat";
            var m = AssetDatabase.LoadAssetAtPath<Material>(p);
            if (m == null) { m = new Material(shader) { name = name }; AssetDatabase.CreateAsset(m, p); }
            m.shader = shader;
            m.shaderKeywords = new string[0];
            return m;
        }

        public static readonly string[] DisplayObjects = { "DISPLAY_Cluster", "DISPLAY_Infotainment", "DISPLAY_Tachograph", "DISPLAY_Radio", "DISPLAY_BunkPanel" };

        static Dictionary<string, TruckMaterialSet> BuildMaterials(Dictionary<string, object> inn)
        {
            var ext = Shader.Find("Kamion/Truck Exterior");
            var glass = Shader.Find("Kamion/Truck Glass");
            var cab = Shader.Find("Kamion/Cab Interior");
            var unlit = Shader.Find("Universal Render Pipeline/Unlit");
            var display = Shader.Find("Kamion/Cab Display");
            var lit = Shader.Find("Universal Render Pipeline/Lit");
            if (ext == null || glass == null || cab == null || display == null) throw new InvalidOperationException("truck shaders not compiled (Kamion/Truck Exterior, Truck Glass, Cab Interior)");
            Directory.CreateDirectory(Path.Combine(EditorTools.ProjectRoot, ResDir));
            var sets = new Dictionary<string, TruckMaterialSet>();
            foreach (var tier in Tiers)
            {
                string dir = $"{MatDir}/{tier}";
                Directory.CreateDirectory(Path.Combine(EditorTools.ProjectRoot, dir));
                var entries = new List<TruckMaterialSet.Entry>();
                void Add(string slot, Material m) { EditorUtility.SetDirty(m); entries.Add(new TruckMaterialSet.Entry { slot = slot, material = m }); }
                string et = $"{SrcExt}/Textures/{tier}";
                foreach (var slot in new[] { "Paint", "Trim", "Metal", "Lights" })
                {
                    var m = Mat(dir, "MI_Ext_" + slot, ext);
                    m.SetTexture("_CMap", Tex<Texture2D>($"{et}/T_Ext_{slot}_C.png"));
                    m.SetTexture("_NMap", Tex<Texture2D>($"{et}/T_Ext_{slot}_N.png"));
                    m.SetTexture("_MMap", Tex<Texture2D>($"{et}/T_Ext_{slot}_M.png"));
                    m.SetFloat("_IsPaint", slot == "Paint" ? 1f : 0f);
                    m.SetFloat("_Dirt", 0.5f);
                    m.SetColor("_DirtColor", new Color(0.15f, 0.135f, 0.11f, 1f));
                    // ADR 0038: coated base lobe, orange peel, procedural road grime (vehicle frame from ContactShadowCaster). WORKING_VALUE.
                    m.SetFloat("_CoatedBaseRoughness", 0.6f); m.SetFloat("_OrangePeel", 0.012f);
                    m.SetFloat("_GrimeHeight", 0.8f); m.SetFloat("_GrimeChassis", 1.3f);
                    if (slot == "Paint")
                    {
                        // Livery "white" (biel flotowa), manifest liveries.white; colours are linear.
                        m.SetTexture("_DecalMap", Tex<Texture2D>($"{et}/T_Ext_Decal.png"));
                        m.SetColor("_PaintColor", new Color(0.78f, 0.785f, 0.78f, 1f));
                        // Base coat under a clear coat (review r3 E1): base 0.36, coat 0.08, F0 0.04 (shader).
                        m.SetFloat("_PaintRoughness", 0.36f); m.SetFloat("_PaintMetallic", 0f);
                        m.SetFloat("_ClearCoat", 1f); m.SetFloat("_ClearCoatRoughness", 0.08f); m.SetFloat("_Flake", 0f);
                        m.SetColor("_DecalColor", new Color(0.1f, 0.104f, 0.11f, 1f));
                        m.SetFloat("_DecalMetallic", 1f); m.SetFloat("_DecalRoughness", 0.3f);
                    }
                    m.SetFloat("_Lamps", slot == "Lights" ? 1f : 0f);
                    if (slot == "Lights") m.EnableKeyword("_KAMION_TRUCK_LAMPS");
                    Add("MI_Ext_" + slot, m);
                }
                var g = Mat(dir, "MI_Ext_Glass", glass);
                // Laminated green windscreen: visible transmittance ~0.78 incl. reflection (EU >= 0.75), so 0.16 absorption;
                // road film outside the wiper sweeps (pivots: manifest WIPER_L/R rig_local_position, glass object space).
                g.SetFloat("_UseVertexColor", 1f); g.SetFloat("_Opacity", 0.16f); g.SetFloat("_Smoothness", 0.96f); g.SetFloat("_Grime", 0f);
                g.SetFloat("_Wiper", 0.35f);
                g.SetVector("_WiperPivotA", new Vector4(-1.0f, 0.87f, 0.18f, 0.95f));
                g.SetVector("_WiperPivotB", new Vector4(-0.08f, 0.87f, 0.18f, 0.95f));
                g.SetVector("_WiperSweep", new Vector4(-5f, 100f, 0.8f, 2.0f));
                g.SetFloat("_WindscreenMinZ", 0.95f);
                g.SetVector("_CabCentreOS", new Vector4(0f, 1.0f, -0.6f, 0f));
                // Review r6 E2: from outside only ~0.7 x cab occlusion 0.6 of the cab behind the glazing reaches the eye (shader).
                g.SetFloat("_ExteriorTransmission", ExtTransmission);
                g.SetFloat("_SeeThroughClutter", 0.35f);
                g.renderQueue = (int)RenderQueue.Transparent;
                Add("MI_Ext_Glass", g);
                // ADR 0059 (r7 N-3): door glass = toughened side glass, no wiper film (the windscreen film made the door
                // glass seen from the seat a milky foil: sat behind it 55 % of the open view). Visible transmittance of
                // light-green side glass ~0.80 incl. reflection -> absorption ~0.12 (WORKING_VALUE; EU front side >= 0.70).
                // One material per door: _CabCentreOS (inside / outside face test) is in the glass object space, and the door
                // glass sits under DOOR_L / DOOR_R with its own pivot - the windscreen value (0, 1, -0.6) lies in the door
                // glass plane there, so the inner face was shaded as an OUTSIDE face from the seat (capture reflection, body
                // haze and the 0.42 exterior transmission in the 1.6-3.2 m band = the milky upper band of r7 N-3). The
                // door-space centre is set below once the hierarchy exists.
                foreach (var side in new[] { "L", "R" })
                {
                    var dg = Mat(dir, "MI_Ext_DoorGlass" + side, glass);
                    dg.CopyPropertiesFromMaterial(g);
                    dg.SetFloat("_Wiper", 0f); dg.SetFloat("_Opacity", 0.12f);
                    dg.renderQueue = (int)RenderQueue.Transparent;
                    Add("MI_Ext_DoorGlass" + side, dg);
                }
                // Main mirrors: unlit, the render texture replaces the idle colour (RenderTextureMirror).
                var mrt = Mat(dir, "MI_Ext_MirrorRT", unlit);
                mrt.SetColor("_BaseColor", GrayboxMaterials.MirrorIdleColor);
                Add("MI_Ext_MirrorRT", mrt);
                // Wide-angle, kerb and front mirrors: placeholder reflection of the environment probe until they get
                // render textures (review r2 A6 #4: never a flat white card). Metallic mirror, slight loss.
                var mp = Mat(dir, "MI_Ext_MirrorProbe", lit);
                mp.SetColor("_BaseColor", new Color(0.82f, 0.83f, 0.85f, 1f));
                mp.SetFloat("_Metallic", 1f); mp.SetFloat("_Smoothness", 0.93f);
                Add("MI_Ext_MirrorProbe", mp);

                // Interior: tier = LOD (High LOD0, Medium LOD1, Low LOD2); AO atlas of that LOD at the tier size.
                int il = TruckVisualRig.InteriorLodFor(tier);
                string it = $"{SrcInt}/Textures/{tier}";
                // AO atlas no smaller than Medium (1024): the LOD0 atlas is packed for 4096, and at the Low 512 the thin
                // islands (A-pillar trim, steering-wheel rim) fall into the black gutter - review r4 L1, Low cab-dash
                // overcast < 3 %: 12.1 % of the frame (512) vs 2.1 % (1024). Cost on Low: +0.26 MB (ASTC 8x8 with mips).
                var ao = Tex<Texture2D>($"{SrcInt}/Textures/{(tier == "Low" ? "Medium" : tier)}/T_Cab_AO_LOD{il}.png");
                foreach (var slot in new[] { "Plastic", "Leather", "Fabric", "Rubber", "Metal" })
                {
                    var m = Mat(dir, "MI_Cab_" + slot, cab);
                    m.SetTexture("_Detail", Tex<Texture2D>($"{it}/T_Cab_{slot}_Detail.png"));
                    m.SetTexture("_Normal", Tex<Texture2D>($"{it}/T_Cab_{slot}_Normal.png"));
                    m.SetTexture("_AO", ao);
                    m.SetFloat("_IsDecal", 0f);
                    // ADR 0044 r8: worn black parts go neutral grey + satin (leather), see CabWearModel
                    m.SetFloat("_WearBlackAlbedo", CabWearModel.WornBlackAlbedo);
                    m.SetFloat("_WearRoughMin", CabWearModel.RoughMinFor(slot));
                    Add("MI_Cab_" + slot, m);
                }
                var dec = Mat(dir, "MI_Cab_Decal", cab);
                dec.SetTexture("_DecalAtlas", Tex<Texture2D>($"{it}/T_Cab_Decal.png"));
                dec.SetTexture("_AO", ao);
                dec.SetFloat("_Cutoff", 0.5f);
                dec.SetFloat("_IsDecal", 1f);
                dec.EnableKeyword("_KAMION_CAB_DECAL");
                dec.renderQueue = (int)RenderQueue.AlphaTest;
                Add("MI_Cab_Decal", dec);
                var cg = Mat(dir, "MI_Cab_Glass", glass);
                cg.SetFloat("_UseVertexColor", 1f); cg.SetFloat("_Opacity", 0.06f); cg.SetFloat("_Smoothness", 0.95f);
                cg.SetTexture("_GrimeMap", Tex<Texture2D>($"{it}/T_Cab_GlassGrime.png"));
                // Cluster cover glass: no grime - the haze texture over the screen read as a grey noisy slab (review r3 C1).
                cg.SetFloat("_Grime", 0f);
                cg.renderQueue = (int)RenderQueue.Transparent;
                cg.SetFloat("_ExteriorTransmission", 1f);   // cluster cover glass: no exterior attenuation
                cg.SetFloat("_SeeThroughClutter", 1f);
                Add("MI_Cab_Glass", cg);
                foreach (var d in DisplayObjects)
                {
                    string tex = d == "DISPLAY_Cluster" ? "T_Display_cluster" : d == "DISPLAY_Infotainment" ? "T_Display_infotainment" : "T_Display_din";
                    // Backlit LCD in exposed units with a readability floor (Kamion/Cab Display, review r3 C1). WORKING_VALUE.
                    var m = Mat(dir, "MI_Cab_" + d, display);
                    m.SetTexture("_BaseMap", Tex<Texture2D>($"{SrcInt}/Textures/Displays/{tex}.png"));
                    m.SetFloat("_Luminance", 500f);
                    m.SetFloat("_MinDisplay", 0.45f);
                    m.SetFloat("_MaxDisplay", 0.9f);
                    m.SetFloat("_Reflection", 0.1f);   // sky reflection mostly occluded by the cluster hood / dash top
                    Add("MI_Cab_Display:" + d, m);
                }

                string setPath = $"{ResDir}/TruckMaterials_{tier}.asset";
                var set = AssetDatabase.LoadAssetAtPath<TruckMaterialSet>(setPath);
                if (set == null) { set = ScriptableObject.CreateInstance<TruckMaterialSet>(); AssetDatabase.CreateAsset(set, setPath); }
                set.entries = entries.ToArray();
                EditorUtility.SetDirty(set);
                sets[tier] = set;
            }
            AssetDatabase.SaveAssets();
            return sets;
        }

        // ------------------------------------------------------------------ 4. prefab

        static Vector3 V3(object o) { var a = Json.Arr(o); return new Vector3((float)Json.Num(a[0]), (float)Json.Num(a[1]), (float)Json.Num(a[2])); }

        static Transform FindDeep(Transform t, string name)
        {
            if (t.name == name) return t;
            foreach (Transform c in t) { var r = FindDeep(c, name); if (r != null) return r; }
            return null;
        }

        static GameObject InstantiateModel(string path, Transform parent)
        {
            var asset = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (asset == null) throw new FileNotFoundException("model not imported: " + path);
            var go = UnityEngine.Object.Instantiate(asset);
            go.name = Path.GetFileNameWithoutExtension(path);
            go.transform.SetParent(parent, false);
            go.transform.localPosition = Vector3.zero;
            go.transform.localRotation = Quaternion.identity;
            go.transform.localScale = Vector3.one;
            return go;
        }

        static void BuildPrefab(Dictionary<string, object> ext, Dictionary<string, object> inn, Dictionary<string, TruckMaterialSet> sets)
        {
            var data = AssetDatabase.LoadAssetAtPath<VehicleDataAsset>("Assets/_Project/Vehicle/Runtime/Resources/" + VehicleDataAsset.DefaultResourcePath + ".asset");
            if (data == null) throw new FileNotFoundException("VehicleData asset missing: run Kamion/Setup/Rebuild DrivingLab");
            var dims = DrivingLabSceneBuilder.ReadAndCheckDims();
            var body = GrayboxTractorBuilder.Build(data, dims, null);
            var root = body.gameObject;
            root.name = "Tractor4x2_TRAKT";
            var visuals = root.GetComponent<VehicleVisuals>();
            var probe = data.CreateModel();
            var def = data.Vehicle;
            try
            {
                // ---- strip the graybox visuals (physics components, colliders, wheel pivots and the coupling camera stay) ----
                UnityEngine.Object.DestroyImmediate(root.transform.Find("Chassis").gameObject);
                UnityEngine.Object.DestroyImmediate(root.transform.Find("CabPivot").gameObject);
                foreach (var spin in visuals.wheelSpinners)
                    for (int i = spin.childCount - 1; i >= 0; i--) UnityEngine.Object.DestroyImmediate(spin.GetChild(i).gameObject);

                // ---- cab suspension pivot at the physics mount centre; cab body at the art CAB_MOUNT_REF ----
                Vector3 mount = new Vector3((float)def.cab.mountCenter.x, (float)def.cab.mountCenter.y, (float)def.cab.mountCenter.z);
                Vector3 artMount = V3(Json.Obj(ext["cab_body"])["unity_vehicle"]);
                var cabSusp = Child(root.transform, "CabSuspension", mount);
                var cabBody = Child(cabSusp, "CabBody", artMount - mount);
                if ((artMount - mount).sqrMagnitude > 1e-6f)
                    Debug.LogWarning($"[TRUCK] cab mount: art {artMount} != physics {mount} (visual offset kept, physics unchanged)");
                visuals.cabPivot = cabSusp;
                visuals.applyCabHeave = true;
                var chassis = Child(root.transform, "Chassis", Vector3.zero);

                // ---- wheel pivots by role (physics order) ----
                var pivotByRole = new Dictionary<string, (Transform pivot, Transform spin)>();
                for (int i = 0; i < probe.Wheels.Length; i++)
                {
                    var w = probe.Wheels[i];
                    var hp = w.HardpointLocal.ToUnity();
                    string role = (hp.z > probe.Wheels.Max(x => (float)x.HardpointLocal.ToUnity().z) - 0.5f ? "F" : "R") + (hp.x < 0 ? "L" : "R");
                    pivotByRole[role] = (visuals.wheelPivots[i], visuals.wheelSpinners[i]);
                }

                // ---- exterior: three LOD files, flat; rebuild the rig from rig_parent ----
                var lods = Json.Obj(ext["lods"]);
                var exteriorLods = new List<Renderer>[3];
                var glassLods = new List<Renderer>[3];   // GLASS_* (windscreen, door glass): own LOD group, LOD0 near on every tier (ADR 0045)
                var lod0ByRole = new Dictionary<string, Transform>();
                var eyeLocal = Vector3.zero;
                var rendererSlots = new List<TruckVisualRig.RendererSlots>();
                var mirrorGlass = new Dictionary<string, Renderer>();
                var mirrorInfo = new Dictionary<string, Dictionary<string, object>>();
                for (int lod = 0; lod < 3; lod++)
                {
                    exteriorLods[lod] = new List<Renderer>();
                    glassLods[lod] = new List<Renderer>();
                    var L = Json.Obj(lods["LOD" + lod]);
                    var model = InstantiateModel($"{SrcExt}/{Path.GetFileName(Json.Str(L["file"]))}", root.transform);
                    var objs = Json.Obj(L["objects"]);
                    // Process parents before children (CAB_Body before DOOR before GLASS_Door; STEER before WHEEL_F).
                    var order = objs.Keys.OrderBy(k => Depth(objs, k)).ToList();
                    foreach (var name in order)
                    {
                        var o = Json.Obj(objs[name]);
                        string role = Json.Str(o["role"]);
                        var t = FindDeep(model.transform, name);
                        if (t == null) { Debug.LogWarning($"[TRUCK] {name} not in the FBX"); continue; }
                        bool isMirror = role.StartsWith("MIRROR_", StringComparison.Ordinal);
                        if (isMirror && lod > 0) { UnityEngine.Object.DestroyImmediate(t.gameObject); continue; }
                        Transform parent;
                        if (lod > 0 && lod0ByRole.TryGetValue(role, out var lod0t)) parent = lod0t;   // rig_note: LOD1-2 under the LOD0 transform of the role
                        else if (role == "CAB_Body") parent = cabBody;
                        else if (role.StartsWith("STEER_", StringComparison.Ordinal)) parent = pivotByRole[role.Substring(6)].pivot;
                        else if (role.StartsWith("WHEEL_", StringComparison.Ordinal)) parent = pivotByRole[role.Substring(6)].spin;
                        else if (isMirror) parent = lod0ByRole["CAB_Body"];
                        else
                        {
                            string rp = Json.Str(o["rig_parent"]);
                            string rpRole = rp.EndsWith("_LOD" + lod, StringComparison.Ordinal) ? rp.Substring(0, rp.Length - 5) : rp;
                            parent = lod0ByRole.TryGetValue(rpRole, out var pt) ? pt : chassis;
                        }
                        t.SetParent(parent, true);
                        if (lod == 0 && role.StartsWith("WHEEL_", StringComparison.Ordinal))
                        {
                            // Wheel centre = physics wheel centre (spin pivot); art static centre height differs by ~1 cm.
                            t.localPosition = Vector3.zero; t.localRotation = Quaternion.identity;
                        }
                        else if (lod == 0 && role.StartsWith("STEER_", StringComparison.Ordinal))
                        {
                            // Knuckle relative to the wheel centre as modelled (kingpin 5 cm inboard).
                            var wheelArt = V3(Json.Obj(objs["WHEEL_" + role.Substring(6) + "_LOD0"])["pivot_unity_vehicle"]);
                            t.localPosition = V3(o["pivot_unity_vehicle"]) - wheelArt; t.localRotation = Quaternion.identity;
                        }
                        else if (lod > 0 && (role.StartsWith("WHEEL_", StringComparison.Ordinal) || role.StartsWith("STEER_", StringComparison.Ordinal)))
                        {
                            t.localPosition = Vector3.zero; t.localRotation = Quaternion.identity;   // same pivot as the LOD0 part
                        }
                        if (lod == 0) lod0ByRole[role] = t;
                        var r = t.GetComponent<Renderer>();
                        if (r != null)
                        {
                            bool transparent = role.StartsWith("GLASS_", StringComparison.Ordinal);
                            if (isMirror)
                            {
                                mirrorInfo[role] = o;
                                // Every mirror gets a render texture (review r5 C5: the wide-angle mirror was a grey probe card).
                                r.sharedMaterial = sets["Low"].Get("MI_Ext_MirrorRT");
                                r.shadowCastingMode = ShadowCastingMode.Off;
                                r.receiveShadows = false;
                                mirrorGlass[role] = r;
                                continue;   // mirror quads are outside the LODGroup (one per mirror, 2 tris)
                            }
                            var slotNames = r.sharedMaterials.Select(m => m != null ? m.name.Replace(" (Instance)", "") : "MI_Ext_Trim").ToArray();
                            // ADR 0059 (r7 N-3): side glass has its own material (no wiper road film, side-glass absorption).
                            if (role.StartsWith("GLASS_Door", StringComparison.Ordinal))
                            {
                                string dslot = "MI_Ext_DoorGlass" + (role.StartsWith("GLASS_DoorL", StringComparison.Ordinal) ? "L" : "R");
                                slotNames = slotNames.Select(s => s == "MI_Ext_Glass" ? dslot : s).ToArray();
                            }
                            rendererSlots.Add(new TruckVisualRig.RendererSlots { renderer = r, slots = slotNames });
                            r.sharedMaterials = slotNames.Select(s => sets["Low"].Get(s)).ToArray();
                            bool glassish = transparent || slotNames.All(s => s == "MI_Ext_Glass");
                            r.shadowCastingMode = glassish ? ShadowCastingMode.Off : ShadowCastingMode.On;
                            r.receiveShadows = !glassish;
                            // Wheels (origin = wheel centre): tyre contact-patch flattening in Kamion/Truck Exterior.
                            if (role.StartsWith("WHEEL_", StringComparison.Ordinal)) r.renderingLayerMask |= TruckVisualRig.TyreRenderingLayer;
                            (transparent ? glassLods : exteriorLods)[lod].Add(r);
                        }
                    }
                    // Empties (LOD0 only: lights, eye point, sockets) under their rig parents; drop LOD1-2 copies and collision.
                    var empties = Json.Obj(L["empties"]);
                    foreach (var e in empties)
                    {
                        var t = FindDeep(model.transform, e.Key);
                        if (t == null) continue;
                        if (lod > 0) { UnityEngine.Object.DestroyImmediate(t.gameObject); continue; }
                        string rp = Json.Str(Json.Obj(e.Value)["rig_parent"]);
                        string rpRole = rp.EndsWith("_LOD0", StringComparison.Ordinal) ? rp.Substring(0, rp.Length - 5) : rp;
                        t.SetParent(lod0ByRole.TryGetValue(rpRole, out var pt) ? pt : chassis, true);
                        if (e.Key == "EYE_POINT") eyeLocal = V3(Json.Obj(e.Value)["position_unity_vehicle"]);
                    }
                    UnityEngine.Object.DestroyImmediate(model);
                }

                // ---- one glass layer (ADR 0048): drop only the body glass faces that duplicate the GLASS_* glazing (centroid inside a
                // glazing renderer's bounds + 2 cm); lamp lens covers (also MI_Ext_Glass, a6_export slot_of lens_clear) are kept. ----
                if (EditorTools.Arg("-keepBodyGlass", null) != "1")
                {
                    var gb = glassLods.SelectMany(l => l).Where(g => g != null).Select(g => { var b = g.bounds; b.Expand(0.04f); return b; }).ToArray();
                    for (int si = 0; si < rendererSlots.Count; si++)
                    {
                        var rs = rendererSlots[si];
                        var br = rs.renderer;
                        if (br == null || br.name.StartsWith("GLASS_", StringComparison.Ordinal) || !rs.slots.Contains("MI_Ext_Glass")) continue;
                        var bmf = br.GetComponent<MeshFilter>();
                        if (bmf == null) continue;
                        var stripped = StripGlassSubmeshes(bmf.sharedMesh, rs.slots, br.transform.localToWorldMatrix, gb, out var keptSlots);
                        if (stripped == null) continue;
                        bmf.sharedMesh = stripped;
                        rs.slots = keptSlots;
                        rendererSlots[si] = rs;
                        br.sharedMaterials = keptSlots.Select(n => sets["Low"].Get(n)).ToArray();
                    }
                }

                // ADR 0104: only the detailed housing embeds the adjusted glass; Low/Medium body meshes stay unchanged.
                RecessMirrorBacking(root.transform, exteriorLods[0].FirstOrDefault(r => r.name.StartsWith("CAB_Body", StringComparison.Ordinal)), mirrorInfo);

                // ---- cab glazing seen from the eye (ADR 0045): the exterior FBX glass is a single outward-facing sheet, so with
                // Kamion/Truck Glass (Cull Back) the driver looked through no glass at all on every tier (no tint, no dash
                // reflection, no road film). Kamion/Truck Glass expects an inside face (normal towards the cab), so add one
                // here when the export has none; skipped automatically once the export ships double-sided glass. ----
                {
                    Vector3 eyeW0 = root.transform.TransformPoint(eyeLocal);
                    foreach (var r in glassLods.SelectMany(l => l))
                    {
                        var mf = r.GetComponent<MeshFilter>();
                        if (mf == null || mf.sharedMesh == null) continue;
                        var ds = DoubleSidedGlass(mf.sharedMesh, r.transform.InverseTransformPoint(eyeW0));
                        if (ds != null) mf.sharedMesh = ds;
                    }
                }

                // ---- ADR 0059 (r7 N-3): cab centre for the door glass inside / outside test, in each door glass's own
                // object space (the windscreen material's _CabCentreOS is in the cab body space). ----
                {
                    var ws = glassLods[0].FirstOrDefault(r => r != null && r.name.StartsWith("GLASS_Windscreen", StringComparison.Ordinal));
                    if (ws != null)
                    {
                        Vector3 cabCentreW = ws.transform.TransformPoint((Vector3)sets["Low"].Get("MI_Ext_Glass").GetVector("_CabCentreOS"));
                        foreach (var side in new[] { "L", "R" })
                        {
                            var door = glassLods[0].FirstOrDefault(r => r != null && r.name.StartsWith("GLASS_Door" + side, StringComparison.Ordinal));
                            if (door == null) { Debug.LogWarning("[TRUCK] GLASS_Door" + side + " missing"); continue; }
                            Vector3 c = door.transform.InverseTransformPoint(cabCentreW);
                            foreach (var tier in Tiers)
                            {
                                var dm = sets[tier].Get("MI_Ext_DoorGlass" + side);
                                dm.SetVector("_CabCentreOS", new Vector4(c.x, c.y, c.z, 0f));
                                EditorUtility.SetDirty(dm);
                            }
                            Debug.Log($"[TRUCK] door glass {side}: cab centre in door space {c}");
                        }
                    }
                }

                // ---- fifth wheel at the PHYSICS kingpin lock (ADR 0019: lead 0.68 m). The exterior export still models the
                // plate inside CHASSIS at the art FIFTH_WHEEL_KINGPIN (0.55 m): until the re-export, an interim plate + kingpin
                // jaw marker sits at the physics position, 3 mm above the art plate top so it wins the depth test; the art plate
                // only shows behind it under the trailer. Removed automatically once the art socket matches the physics. ----
                {
                    Vector3 fwPhys = new Vector3((float)def.fifthWheel.position.x, (float)def.fifthWheel.position.y, (float)def.fifthWheel.position.z);
                    var fwEmpty = Json.Obj(Json.Obj(Json.Obj(lods["LOD0"])["empties"])["FIFTH_WHEEL_KINGPIN"]);
                    Vector3 fwArt = V3(fwEmpty["position_unity_vehicle"]);
                    var socket = Child(chassis, "FifthWheel_Physics", fwPhys);   // kingpin lock point (jaw centre), physics frame
                    if ((fwArt - fwPhys).magnitude > 0.01f)
                    {
                        Debug.LogWarning($"[TRUCK] fifth wheel: art FIFTH_WHEEL_KINGPIN {fwArt} != physics {fwPhys} (dims.json fifth_wheel_lead_m); interim plate at the physics position until the exterior re-export");
                        string mp = $"{MatDir}/MI_FifthWheel_Interim.mat";
                        var fm = AssetDatabase.LoadAssetAtPath<Material>(mp);
                        if (fm == null) { fm = new Material(Shader.Find("Universal Render Pipeline/Lit")) { name = "MI_FifthWheel_Interim" }; AssetDatabase.CreateAsset(fm, mp); }
                        // Greased black cast steel: albedo 0.035 linear, smoothness 0.45 (grease film). WORKING_VALUE.
                        fm.SetColor("_BaseColor", new Color(0.035f, 0.035f, 0.033f, 1f)); fm.SetFloat("_Metallic", 0.6f); fm.SetFloat("_Smoothness", 0.45f);
                        EditorUtility.SetDirty(fm);
                        Mesh cyl = Resources.GetBuiltinResource<Mesh>("New-Cylinder.fbx");
                        void Part(string n, Vector3 lp, Vector3 scale)
                        {
                            var go = new GameObject(n, typeof(MeshFilter), typeof(MeshRenderer));
                            go.transform.SetParent(socket, false);
                            go.transform.localPosition = lp; go.transform.localScale = scale;
                            go.GetComponent<MeshFilter>().sharedMesh = cyl;
                            var mr = go.GetComponent<MeshRenderer>();
                            mr.sharedMaterial = fm; mr.shadowCastingMode = ShadowCastingMode.On;
                        }
                        // Plate 0.86 m diameter (class-typical 50 mm kingpin couplings, WORKING_VALUE), 6 cm thick, top 3 mm above the lock plane.
                        Part("Plate", new Vector3(0f, 0.003f - 0.03f, 0f), new Vector3(0.86f, 0.03f, 0.86f));
                        // Bracket / bearing block under the plate down to the frame top.
                        float frameTop = dims.frameTopHeight;
                        float h = Mathf.Max(0.02f, fwPhys.y - 0.06f - frameTop);
                        Part("Bracket", new Vector3(0f, -0.06f - h * 0.5f, 0f), new Vector3(0.5f, h * 0.5f, 0.5f));
                    }
                }

                // ---- driver eye point (camera anchor: DrivingLabBootstrap looks for cabPivot/DriverEyePoint) ----
                var eye = Child(cabSusp, "DriverEyePoint", eyeLocal - mount);
                if ((eyeLocal - dims.EyePointVehicle).sqrMagnitude > 1e-6f)
                    Debug.LogWarning($"[TRUCK] EYE_POINT {eyeLocal} != dims.json driver eye {dims.EyePointVehicle}");

                // ---- interior: CabInterior_LODn roots at CAB_MOUNT_REF (= CabBody), placeholders removed ----
                var interiorLods = new List<Renderer>[3];
                var ilods = Json.Obj(inn["lods"]);
                // ---- seat H-point (interior manifest H_POINT, cab-local) as a marker on the cab-suspension pivot, so tests and the
                // camera rig can assert eye - H-point (ADR 0052). Same cab frame as EYE_POINT: H = vehicle eye + (H_cab - EYE_cab). ----
                {
                    var emp = Json.Obj(Json.Obj(ilods["LOD0"])["empties_unity_local"]);
                    Vector3 hCab = V3(emp["H_POINT"]), eCab = V3(emp["EYE_POINT"]);
                    Child(cabSusp, "DriverHPoint", eyeLocal + (hCab - eCab) - mount);
                }
                var wheelCentre = V3(Json.Obj(Json.Obj(ilods["LOD0"])["empties_unity_local"])["WHEEL_CENTRE"]);
                var steerAxis = new Vector3(0f, 0.78801f, -0.61566f);   // manifest STEERING_WHEEL steer axis_unity_cab (local +Y, towards the driver)
                var column = Child(cabBody, "SteeringColumn", wheelCentre);
                column.localRotation = Quaternion.LookRotation(-steerAxis, Vector3.up);   // local +Z = column axis away from the driver
                visuals.steeringWheel = column;
                var interiorRoot = Child(cabBody, "Interior", Vector3.zero);
                for (int lod = 0; lod < 3; lod++)
                {
                    interiorLods[lod] = new List<Renderer>();
                    var L = Json.Obj(ilods["LOD" + lod]);
                    var model = InstantiateModel($"{SrcInt}/{Path.GetFileName(Json.Str(L["file"]))}", interiorRoot);
                    foreach (var r in model.GetComponentsInChildren<Renderer>(true).ToArray())
                    {
                        string n = r.name;
                        if (n.StartsWith("CAB_ShellPlaceholder", StringComparison.Ordinal) || n.StartsWith("CAB_Glass_Windows", StringComparison.Ordinal) ||
                            n.StartsWith("MIRROR_", StringComparison.Ordinal) || n.StartsWith("CAB_Glass_LOD", StringComparison.Ordinal))
                        {
                            // The exterior owns the skin, the glazing and the mirrors (glass_interface.json); the shell placeholder was
                            // the white band seen through the windscreen in the A6 URP-like renders (review r2 A6 #2).
                            // CAB_Glass (cluster cover glass): its unoccluded sky Fresnel greyed the screen to 4-6:1 (review r3 C1);
                            // Kamion/Cab Display carries the (hood-occluded) cover reflection itself.
                            UnityEngine.Object.DestroyImmediate(r.gameObject);
                            continue;
                        }
                        string[] slotNames;
                        string disp = DisplayObjects.FirstOrDefault(d => n.StartsWith(d + "_", StringComparison.Ordinal));
                        if (disp != null) slotNames = new[] { "MI_Cab_Display:" + disp };
                        else slotNames = r.sharedMaterials.Select(m => m != null ? m.name.Replace(" (Instance)", "") : "MI_Cab_Plastic").ToArray();
                        r.sharedMaterials = slotNames.Select(s => sets["Low"].Get(s) ?? sets["Low"].Get("MI_Cab_Plastic")).ToArray();
                        rendererSlots.Add(new TruckVisualRig.RendererSlots { renderer = r, slots = slotNames });
                        bool flat = disp != null || slotNames.All(s => s == "MI_Cab_Glass");
                        r.shadowCastingMode = flat ? ShadowCastingMode.Off : ShadowCastingMode.On;
                        r.receiveShadows = !flat;
                        if (n.StartsWith("STEERING_WHEEL", StringComparison.Ordinal)) r.transform.SetParent(column, true);
                        interiorLods[lod].Add(r);
                    }
                    foreach (var e in new[] { "EYE_POINT", "H_POINT", "WHEEL_CENTRE", "CAB_MOUNT_REF" })
                    {
                        var t = FindDeep(model.transform, e);
                        if (t != null && lod > 0) UnityEngine.Object.DestroyImmediate(t.gameObject);
                    }
                }

                // ---- mirrors: render texture on every mirror, camera at the mirror image of the eye (ADR 0042) ----
                // UN ECE R46 classes: main II (r >= 1200 mm), wide-angle IV, kerb V, front VI (r >= 300 mm). Radii are
                // WORKING_VALUE within those minima, chosen so the class II / IV fields of vision (R46 Annex/para 15.2.4,
                // paragraph numbers UNVERIFIED) are covered from the design eye point (ADR 0042 table).
                Vector3 eyeW = root.transform.TransformPoint(eyeLocal);
                int phase = 0;
                foreach (var role in new[] { "MIRROR_MainL", "MIRROR_MainR", "MIRROR_WideL", "MIRROR_WideR", "MIRROR_Kerb", "MIRROR_Front" })
                {
                    float radius = MirrorRadius(role);
                    bool main = role.StartsWith("MIRROR_Main", StringComparison.Ordinal);
                    if (!mirrorGlass.TryGetValue(role, out var r)) { Debug.LogWarning("[TRUCK] " + role + " missing"); continue; }
                    var o = mirrorInfo[role];
                    var size = Json.Arr(o["size_m"]);
                    float gw = (float)Json.Num(size[0]), gh = (float)Json.Num(size[1]);
                    Vector3 q = r.transform.position;
                    Vector3 n = root.transform.TransformDirection(V3(o["normal_unity_vehicle"])).normalized;   // towards the eye
                    Vector3 up = root.transform.TransformDirection(V3(Json.Obj(o["axes_unity_vehicle"])["Y"])).normalized;
                    // Mirror adjustment (what the driver does with the electric adjuster): turn the glass about its centre so
                    // the eye ray through the centre reflects along the class target axis (MirrorAim), at most AdjustRangeDeg
                    // from the modelled glass. Geometry of the housing is untouched (art), only the glass quad turns.
                    var turn = MirrorAdjustment(role, eyeW, q, n, root.transform.rotation, out float adj, out bool clamped);
                    if (clamped) Debug.LogWarning($"[TRUCK] {role}: adjustment {adj:F1} deg exceeds the adjuster range {AdjustRangeDeg} deg (re-aim the modelled glass); clamped");
                    if (adj > 0f)
                    {
                        r.transform.rotation = turn * r.transform.rotation;
                        n = (turn * n).normalized; up = (turn * up).normalized;
                        Debug.Log($"[TRUCK] {role}: glass adjusted {adj:F1} deg (target axis yaw {MirrorAim[role].yaw} pitch {MirrorAim[role].pitch})");
                    }
                    var view = MirrorOptics.Build(eyeW, q, n, up, gw, gh, radius);
                    float dist = view.distance;
                    var camT = Child(lod0ByRole["CAB_Body"], role + "_Camera", Vector3.zero);
                    camT.position = view.position;
                    camT.rotation = Quaternion.LookRotation(view.forward, up);
                    // Convex mirror of radius R: the surface normal at the glass edge (half size s) turns by s / R, so the
                    // reflected ray turns by 2 s / R on top of the flat-mirror angle atan(s / d) (MirrorOptics.Build).
                    var cam = camT.gameObject.AddComponent<Camera>();
                    RenderTextureMirror.ConfigureCheapCamera(cam, 2f * view.HalfVDeg, Mathf.Max(0.1f, dist * 0.98f), 250f);
                    Debug.Log($"[TRUCK] {role}: axis {view.forward:F3}, field {2f * view.HalfHDeg:F1} x {2f * view.HalfVDeg:F1} deg");
                    var mir = camT.gameObject.AddComponent<RenderTextureMirror>();
                    mir.glass = r;
                    mir.flipHorizontally = false; // reflected-eye camera + exported UV basis already produce a mirror image
                    mir.aspect = gw / gh;
                    mir.fovAspect = view.tanHalfH / view.tanHalfV;
                    mir.main = main;
                    mir.weight = main ? 1f : 0.5f;
                    // Convex images are minified: about the main mirror's pixels per glass metre, capped at 0.6 of its height.
                    mir.resolutionScale = main ? 1f : Mathf.Clamp(gh / 0.386f * 1.4f, 0.35f, 0.6f);
                    mir.phase = phase++;
                }

                // ---- LOD groups, tier binding, lamps, cab light ----
                var group = root.AddComponent<LODGroup>();
                group.fadeMode = LODFadeMode.None;
                var igroup = interiorRoot.gameObject.AddComponent<LODGroup>();
                igroup.fadeMode = LODFadeMode.None;
                var rig = root.AddComponent<TruckVisualRig>();
                rig.exteriorGroup = group; rig.interiorGroup = igroup;
                // ADR 0045: the cab glazing is drawn from its own LOD group so the driver always looks through the LOD0
                // windscreen (Low used to show LOD2 glass only, which does not cover the LOD0 cab opening from the eye).
                var ggroup = Child(cabBody, "CabGlassLOD", Vector3.zero).gameObject.AddComponent<LODGroup>();
                ggroup.fadeMode = LODFadeMode.None;
                rig.glassGroup = ggroup;
