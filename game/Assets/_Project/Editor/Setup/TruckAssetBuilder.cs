    /// <summary>
    /// Track A7: builds the TRAKT tractor prefab from the A6 exports (regenerate, never hand-edit). Reads
    /// art-source/truck/exterior/export/truck_exterior_manifest.json and art-source/truck/interior/export/cab_interior_manifest.json:
    /// 1. copies the FBX (exterior LOD0-2, interior LOD0-2) and the per-tier atlases into Assets/_Generated/Truck (outside git,
    ///    like the world regions, ADR 0011; the interior LOD0 FBX itself is generated by Blender, see docs/reports/visual/truck-A7);
    /// 2. import settings: scale 1, convert units, no axis bake, no animation; textures sRGB/linear/normal as the contract
    ///    says, ASTC per tier on Android (manifest tiers.texture_compression);
    /// 3. materials per tier (Kamion/Truck Exterior, Kamion/Truck Glass, Kamion/Cab Interior, URP Unlit/Lit for displays
    ///    and mirrors) in TruckMaterialSet assets; Low is referenced by the prefab, Medium/High load from Resources;
    /// 4. the prefab: the graybox tractor provides the physics root (Rigidbody, VehicleBody, VehicleVisuals, the same box
    ///    colliders and the coupling camera, i.e. physics unchanged); its visuals are replaced by the art, rebuilt from the
    ///    manifest rig_parent hierarchy (the FBX is flat): wheels and knuckles under the physics wheel pivots (spin and steer
    ///    from the solver), cab body + doors + wipers + windscreen + mirrors + interior on the cab-suspension pivot (pitch,
    ///    roll and heave from the solver), steering wheel on a column pivot driven by the handwheel angle, the driver eye
    ///    point from the manifest, render-texture main mirrors and probe-reflection placeholders for the others.
    /// Entry points: Kamion/Setup/Rebuild TRAKT truck, batchmode -executeMethod Game.Editor.Setup.TruckAssetBuilder.BuildBatch
    /// (Game.World.Import.WorldTruckInstaller.InstallBatch puts it into the WorldC scenes).
    /// </summary>
    public static class TruckAssetBuilder
    {
