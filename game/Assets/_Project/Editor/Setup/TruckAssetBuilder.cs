        public static class Json
        {
            public static object Parse(string s) { int i = 0; return Value(s, ref i); }
            public static Dictionary<string, object> Obj(object o) => (Dictionary<string, object>)o;
            public static List<object> Arr(object o) => (List<object>)o;
            public static double Num(object o) => Convert.ToDouble(o, CultureInfo.InvariantCulture);
            public static string Str(object o) => (string)o;

            static void Ws(string s, ref int i) { while (i < s.Length && char.IsWhiteSpace(s[i])) i++; }

            static object Value(string s, ref int i)
            {
                Ws(s, ref i);
                char c = s[i];
                if (c == '{')
                {
                    var d = new Dictionary<string, object>(); i++; Ws(s, ref i);
                    if (s[i] == '}') { i++; return d; }
                    while (true)
                    {
                        Ws(s, ref i); string k = (string)Value(s, ref i); Ws(s, ref i); i++; // ':'
                        d[k] = Value(s, ref i); Ws(s, ref i);
                        if (s[i++] == '}') return d;
                    }
                }
                if (c == '[')
                {
                    var a = new List<object>(); i++; Ws(s, ref i);
