    /// <summary>
    /// Track A7: builds the TRAKT tractor prefab from the A6 exports (regenerate, never hand-edit). Reads
    /// art-source/truck/exterior/export/truck_exterior_manifest.json and art-source/truck/interior/export/cab_interior_manifest.json:
    /// 1. copies the FBX (exterior LOD0-2, interior LOD0-2) and the per-tier atlases into Assets/_Generated/Truck (outside git,
    ///    like the world regions, ADR 0011; the interior LOD0 FBX itself is generated by Blender, see docs/reports/visual/truck-A7);
    /// 2. import settings: scale 1, convert units, no axis bake, no animation; textures sRGB/linear/normal as the contract
    ///    says, ASTC per tier on Android (manifest tiers.texture_compression);
