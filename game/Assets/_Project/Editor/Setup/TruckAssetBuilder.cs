        /// <summary>
        /// Contact shadow of a vehicle (review r4 E-N1). Measured from the built hierarchy, not assumed: wheel radius =
        /// half height of the wheel's renderers, ground = mean wheel contact height in the root frame, footprint = bounds
        /// of the other mesh renderers in the root frame (x clamped to the body width). <paramref name="sections"/> splits
        /// the footprint from the front: (length m or 0 = rest, underside clearance above ground m, strength, rows);
        /// <paramref name="maxLength"/> > 0 limits the footprint to that length from the rear end.
        /// </summary>
        public static ContactShadowCaster AddContactShadow(GameObject root, Transform[] wheelPivots, float maxHalfWidth,
            (float length, float clearance, float strength, int rows)[] sections, float maxLength = 0f, float dualWidth = 0.66f, float singleWidth = 0.34f,
            int columns = 3)
        {
            var t = root.transform;
            var pivots = (wheelPivots ?? new Transform[0]).Where(w => w != null).ToArray();
            var wheelRs = new HashSet<Renderer>(pivots.SelectMany(w => w.GetComponentsInChildren<Renderer>(true)));
            var wheels = new List<ContactShadowCaster.Wheel>();
            float groundSum = 0f;
            foreach (var w in pivots)
            {
                var rs = w.GetComponentsInChildren<Renderer>(true);
                float radius = rs.Length > 0 ? rs.Max(r => r.bounds.extents.y) : 0.5f;
                Vector3 lp = t.InverseTransformPoint(w.position);
                groundSum += lp.y - radius;
                float width = rs.Length > 0 ? rs.Max(r => Mathf.Abs(t.InverseTransformVector(r.bounds.size).x)) : singleWidth;
                wheels.Add(new ContactShadowCaster.Wheel { centre = w, radius = radius, width = Mathf.Clamp(width, singleWidth, dualWidth) });
            }
            float ground = wheels.Count > 0 ? groundSum / wheels.Count : 0f;
            bool any = false; var b = new Bounds();
            foreach (var r in root.GetComponentsInChildren<MeshRenderer>(true))
            {
                if (wheelRs.Contains(r)) continue;
                var lb = r.bounds;
                for (int k = 0; k < 8; k++)
                {
                    var c = new Vector3((k & 1) == 0 ? lb.min.x : lb.max.x, (k & 2) == 0 ? lb.min.y : lb.max.y, (k & 4) == 0 ? lb.min.z : lb.max.z);
                    var p = t.InverseTransformPoint(c);
                    if (!any) { b = new Bounds(p, Vector3.zero); any = true; } else b.Encapsulate(p);
                }
            }
            float hw = Mathf.Min(any ? b.extents.x : maxHalfWidth, maxHalfWidth);
            float zMin = any ? b.min.z : -1f, zMax = any ? b.max.z : 1f;
            if (maxLength > 0f) zMax = Mathf.Min(zMax, zMin + maxLength);   // measured from the rear end
            var slabs = new List<ContactShadowCaster.Slab>();
            float z1 = zMax;
            foreach (var sct in sections)
            {
                float z0 = sct.length > 0f ? Mathf.Max(zMin, z1 - sct.length) : zMin;
                slabs.Add(new ContactShadowCaster.Slab { centre = new Vector2(b.center.x, 0.5f * (z0 + z1)), halfSize = new Vector2(hw - 0.05f, 0.5f * (z1 - z0) - 0.05f),
                    undersideY = ground + sct.clearance, strength = sct.strength, rows = sct.rows, columns = columns });
                z1 = z0;
            }
            var cs = root.GetComponent<ContactShadowCaster>();
            if (cs == null) cs = root.AddComponent<ContactShadowCaster>();
            cs.slabs = slabs.ToArray();
            cs.wheels = wheels.ToArray();
            Debug.Log($"[TRUCK] contact shadow {root.name}: ground y {ground:F2}, footprint z {zMin:F2}..{zMax:F2}, half width {hw:F2}, wheels {wheels.Count} " +
                      $"(r {string.Join("/", wheels.Select(w => w.radius.ToString("F2")))}, w {string.Join("/", wheels.Select(w => w.width.ToString("F2")))})");
            return cs;
        }

        /// <summary>
        /// ADR 0048: copy of a body mesh without the MI_Ext_Glass triangles whose centroid (world space via <paramref name="l2w"/>) lies inside
        /// one of <paramref name="glazing"/> (bounds of the GLASS_* renderers): those duplicate the glazing. Other glass-slot
        /// triangles (lamp lens covers) stay; a submesh left empty is dropped. Saved under Assets/_Generated/Truck/Meshes; null when
        /// nothing is stripped. <paramref name="keptSlots"/> = remaining slot names.
        /// </summary>
        public static Mesh StripGlassSubmeshes(Mesh src, string[] slotNames, Matrix4x4 l2w, Bounds[] glazing, out string[] keptSlots, bool save = true)
        {
            keptSlots = slotNames;
            if (src == null || src.subMeshCount != slotNames.Length) return null;
            var v = src.vertices;
            var tris = new List<int[]>(); var names = new List<string>(); bool removed = false;
            for (int sm = 0; sm < slotNames.Length; sm++)
            {
                var t = src.GetTriangles(sm);
                if (slotNames[sm] == "MI_Ext_Glass")
                {
                    var k = new List<int>();
                    for (int i = 0; i < t.Length; i += 3)
                    {
                        var c = l2w.MultiplyPoint3x4((v[t[i]] + v[t[i + 1]] + v[t[i + 2]]) / 3f);
                        if (glazing.Any(b => b.Contains(c))) { removed = true; continue; }
                        k.Add(t[i]); k.Add(t[i + 1]); k.Add(t[i + 2]);
                    }
                    t = k.ToArray();
                    if (t.Length == 0) continue;
                }
                tris.Add(t); names.Add(slotNames[sm]);
            }
            if (!removed || tris.Count == 0) return null;
            var m = UnityEngine.Object.Instantiate(src);
            m.name = src.name + "_NoGlass";
            m.subMeshCount = tris.Count;
            for (int i = 0; i < tris.Count; i++) m.SetTriangles(tris[i], i);
            m.bounds = src.bounds;
            keptSlots = names.ToArray();
            if (!save) return m;
            string dir = Root + "/Meshes";
            Directory.CreateDirectory(Path.Combine(EditorTools.ProjectRoot, dir));
            string path = $"{dir}/{m.name}.asset";
            var old = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (old != null) { EditorUtility.CopySerialized(m, old); UnityEngine.Object.DestroyImmediate(m); EditorUtility.SetDirty(old); return old; }
            AssetDatabase.CreateAsset(m, path);
            return m;
        }

        // ADR 0104: called only for the detailed exterior body after inspecting the baseline. Low/Medium retain their
        // original body meshes; all tiers retain the exact mirror glass transforms and camera optics.
        static void RecessMirrorBacking(Transform root, Renderer body, Dictionary<string, Dictionary<string, object>> mirrors)
        {
            var filter = body != null ? body.GetComponent<MeshFilter>() : null;
            if (filter == null || filter.sharedMesh == null) return;
            var openings = new List<MirrorHousingRecess.Opening>(2);
            foreach (string side in new[] { "L", "R" })
            {
                if (!mirrors.TryGetValue("MIRROR_Main" + side, out var main) ||
                    !mirrors.TryGetValue("MIRROR_Wide" + side, out var wide)) continue;
                var axes = Json.Obj(main["axes_unity_vehicle"]);
                Vector3 centre = V3(main["pivot_unity_vehicle"]), up = V3(axes["Y"]).normalized;
                var size = Json.Arr(main["size_m"]);
                var wideSize = Json.Arr(wide["size_m"]);
                openings.Add(new MirrorHousingRecess.Opening {
                    centre = centre, right = V3(axes["X"]).normalized, up = up,
                    normal = V3(main["normal_unity_vehicle"]).normalized,
                    halfWidth = (float)Json.Num(size[0]) * 0.5f,
                    bottom = Vector3.Dot(V3(wide["pivot_unity_vehicle"]) - centre, up) - (float)Json.Num(wideSize[1]) * 0.5f,
                    top = (float)Json.Num(size[1]) * 0.5f,
                });
            }
            var source = filter.sharedMesh;
            var mesh = MirrorHousingRecess.Apply(source, root.worldToLocalMatrix * body.transform.localToWorldMatrix, openings, out int moved);
            if (mesh == null) { Debug.Log("[TRUCK] Mirror housing recess: no backing vertices need moving"); return; }
            string dir = Root + "/Meshes";
            Directory.CreateDirectory(Path.Combine(EditorTools.ProjectRoot, dir));
            string path = $"{dir}/{mesh.name}.asset";
            var old = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (old != null)
            {
                EditorUtility.CopySerialized(mesh, old);
                UnityEngine.Object.DestroyImmediate(mesh);
                EditorUtility.SetDirty(old);
                mesh = old;
            }
            else AssetDatabase.CreateAsset(mesh, path);
            filter.sharedMesh = mesh;
            Debug.Log($"[TRUCK] Mirror housing recess {body.name}: moved={moved} vertices={source.vertexCount}->{mesh.vertexCount} indices={source.triangles.Length}->{mesh.triangles.Length}; optics unchanged");
        }

        /// <summary>
        /// ADR 0045: returns a copy of a single-sided glass sheet with an inside face (reversed winding, flipped normals and
        /// tangents) saved under Assets/_Generated/Truck/Meshes, or null when the mesh already has normals facing
        /// <paramref name="eyeOS"/> (the export is double-sided). Same vertex colour / uv, so tint and road film match.
        /// </summary>
        public static Mesh DoubleSidedGlass(Mesh src, Vector3 eyeOS, bool save = true)
        {
            var v = src.vertices; var n = src.normals;
            if (n == null || n.Length != v.Length) return null;
            for (int i = 0; i < v.Length; i++) if (Vector3.Dot(n[i], eyeOS - v[i]) > 0f) return null;
            int nv = v.Length;
            Vector3[] D3(Vector3[] a, bool neg) { var o = new Vector3[a.Length * 2]; for (int i = 0; i < a.Length; i++) { o[i] = a[i]; o[i + a.Length] = neg ? -a[i] : a[i]; } return o; }
            T[] D<T>(T[] a) { if (a == null || a.Length != nv) return null; var o = new T[nv * 2]; a.CopyTo(o, 0); a.CopyTo(o, nv); return o; }
            var m = new Mesh { name = src.name + "_2S", indexFormat = nv * 2 > 65535 ? IndexFormat.UInt32 : IndexFormat.UInt16 };
            m.vertices = D3(v, false);
            m.normals = D3(n, true);
            var tg = src.tangents;
            if (tg != null && tg.Length == nv)
            {
                var t2 = new Vector4[nv * 2];
                for (int i = 0; i < nv; i++) { t2[i] = tg[i]; t2[i + nv] = new Vector4(-tg[i].x, -tg[i].y, -tg[i].z, tg[i].w); }
                m.tangents = t2;
            }
            var c = D(src.colors); if (c != null) m.colors = c;
            for (int ch = 0; ch < 4; ch++)
            {
                var uv = new List<Vector2>(); src.GetUVs(ch, uv);
                if (uv.Count == nv) { var u2 = new List<Vector2>(uv); u2.AddRange(uv); m.SetUVs(ch, u2); }
            }
            m.subMeshCount = src.subMeshCount;
            for (int sm = 0; sm < src.subMeshCount; sm++)
            {
                var t = src.GetTriangles(sm);
                var t2 = new int[t.Length * 2];
                for (int i = 0; i < t.Length; i += 3)
                {
                    t2[i] = t[i]; t2[i + 1] = t[i + 1]; t2[i + 2] = t[i + 2];
                    t2[t.Length + i] = t[i] + nv; t2[t.Length + i + 1] = t[i + 2] + nv; t2[t.Length + i + 2] = t[i + 1] + nv;
                }
                m.SetTriangles(t2, sm);
            }
            m.bounds = src.bounds;
            if (!save) return m;
            string dir = Root + "/Meshes";
            Directory.CreateDirectory(Path.Combine(EditorTools.ProjectRoot, dir));
            string path = $"{dir}/{m.name}.asset";
            var old = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (old != null) { EditorUtility.CopySerialized(m, old); UnityEngine.Object.DestroyImmediate(m); EditorUtility.SetDirty(old); return old; }
            AssetDatabase.CreateAsset(m, path);
            return m;
        }

