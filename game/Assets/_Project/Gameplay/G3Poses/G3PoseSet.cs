using System;
using System.Collections.Generic;
using System.Globalization;

namespace Game.Gameplay
{
    /// <summary>Where a pose comes from (ADR 0246): the photo-pair camera file and its index, never typed by hand.</summary>
    [Serializable]
    public class G3PoseSource
    {
        public string cameras_file;
        public int cameras_index;
        public string references_file;
        public string pose_reason;
        public string note;
    }

    /// <summary>The reference photo of a pose (outside git; only its name, size and attribution travel in the file).</summary>
    [Serializable]
    public class G3PoseReference
    {
        public string photo;
        public string comparison_photo;
        public string source_id;
        public string page_url;
        public string author;
        public string license;
        public string captured_at;
        public int width;
        public int height;
    }

    /// <summary>One photo-pair pose: (E, N, absolute U) position and look-at point in the region frame, vertical FOV.</summary>
    [Serializable]
    public class G3Pose
    {
        public int index;
        public string id;
        public string segment;
        public string kind;
        public string seat;
        public float[] pos;
        public float[] look_at;
        public float fov_deg;
        public string pose_confidence;
        public int out_width;
        public int out_height;
        public G3PoseSource source;
        public G3PoseReference reference;
    }

    [Serializable]
    public class G3PoseFile
    {
        public string schema;
        public string region;
        public string frame;
        public int count;
        public G3Pose[] poses;
    }

    /// <summary>
    /// Pose list of the Gate 3 photo pairs (ADR 0246): Resources/g3_poses.json, generated by
    /// <c>python scripts/g3_poses.py export</c> from Data/Regions/&lt;region&gt;/sbs_cameras.json + sbs_references.json.
    /// Parsing, validation and selection only, no UnityEngine API outside <see cref="Deserialize"/>: the same tests run as
    /// EditMode tests in Unity and as plain .NET tests (tests/g3poses/G3PoseTests.csproj).
    /// </summary>
    public static class G3PoseSet
    {
        public const string Schema = "kamion/g3-poses/1";
        public const string ResourceName = "g3_poses";

        /// <summary>
        /// Parses and validates the file. Invalid poses are dropped with a message in <paramref name="errors"/>; a wrong
        /// schema, a count that does not match the list or an empty list returns null (nothing is captured from a
        /// half-read file).
        /// </summary>
        public static G3PoseFile Parse(string json, List<string> errors)
        {
            errors?.Clear();
            if (string.IsNullOrEmpty(json)) { errors?.Add("empty pose file"); return null; }
            G3PoseFile f;
            try { f = Deserialize(json); }
            catch (Exception e) { errors?.Add("json: " + e.Message); return null; }
            if (f == null) { errors?.Add("json: no object"); return null; }
            if (f.schema != Schema) { errors?.Add($"schema '{f.schema}' != '{Schema}'"); return null; }
            if (f.poses == null || f.poses.Length == 0) { errors?.Add("no poses"); return null; }
            if (f.count != f.poses.Length) { errors?.Add($"count {f.count} != {f.poses.Length} poses"); return null; }

            var ok = new List<G3Pose>(f.poses.Length);
            var ids = new HashSet<string>(StringComparer.Ordinal);
            foreach (var p in f.poses)
            {
                string why = Validate(p);
                if (why == null && !ids.Add(p.id)) why = "duplicate id";
                if (why != null) { errors?.Add($"pose {(p != null ? p.index.ToString(CultureInfo.InvariantCulture) : "?")} '{p?.id}': {why}"); continue; }
                ok.Add(p);
            }
            f.poses = ok.ToArray();
            return f;
        }

        /// <summary>Null when the pose can be rendered, otherwise the reason.</summary>
        public static string Validate(G3Pose p)
        {
            if (p == null) return "null";
            if (string.IsNullOrEmpty(p.id)) return "no id";
            if (p.index < 1) return "index < 1";
            if (!IsVec3(p.pos)) return "pos is not 3 finite numbers";
            if (!IsVec3(p.look_at)) return "look_at is not 3 finite numbers";
            float dx = p.look_at[0] - p.pos[0], dy = p.look_at[1] - p.pos[1], dz = p.look_at[2] - p.pos[2];
            if (dx * dx + dy * dy + dz * dz < 1e-4f) return "look_at == pos";
            if (dx * dx + dy * dy < 1e-6f) return "looks straight up/down (no heading)";
            if (!(p.fov_deg > 1f && p.fov_deg < 179f)) return "fov_deg outside (1, 179)";
            if (!string.IsNullOrEmpty(p.seat) && p.seat != "file" && p.seat != "road") return $"seat '{p.seat}' (file|road)";
            bool hasOut = p.out_width > 0 && p.out_height > 0;
            bool hasRef = p.reference != null && p.reference.width > 0 && p.reference.height > 0;
            if (!hasOut && !hasRef) return "no output size and no reference size";
            return null;
        }

        static bool IsVec3(float[] v)
        {
            if (v == null || v.Length != 3) return false;
            for (int i = 0; i < 3; i++) if (float.IsNaN(v[i]) || float.IsInfinity(v[i])) return false;
            return true;
        }

        /// <summary>
        /// Filter of the launch argument g3pose_only (same rule as scripts/g3_poses.py list --only): comma-separated tokens;
        /// a number of at most <see cref="MaxIndexDigits"/> digits is the 1-based pose index, "a-b" of such numbers is an index
        /// range, any other token (also a longer number such as a photo key "140653") is a case-insensitive substring of
        /// the id with '_' and '-' treated as equal. Empty filter = every pose.
        /// </summary>
        public static bool Matches(G3Pose p, string filter)
        {
            if (string.IsNullOrWhiteSpace(filter)) return true;
            if (p == null) return false;
            string id = Norm(p.id);
            foreach (var raw in filter.Split(','))
            {
                string t = raw.Trim();
                if (t.Length == 0) continue;
                if (TryIndex(t, out int n)) { if (n == p.index) return true; continue; }
                int dash = t.IndexOf('-');
                if (dash > 0 && TryIndex(t.Substring(0, dash), out int a) && TryIndex(t.Substring(dash + 1), out int b))
                {
                    if (p.index >= Math.Min(a, b) && p.index <= Math.Max(a, b)) return true;
                    continue;
                }
                if (id.Contains(Norm(t))) return true;
            }
            return false;
        }

        public const int MaxIndexDigits = 3;

        static bool TryIndex(string t, out int n)
        {
            n = 0;
            if (t.Length == 0 || t.Length > MaxIndexDigits) return false;
            return int.TryParse(t, NumberStyles.None, CultureInfo.InvariantCulture, out n);
        }

        /// <summary>The poses selected by <paramref name="filter"/>, in file order.</summary>
        public static List<G3Pose> Select(G3PoseFile f, string filter)
        {
            var list = new List<G3Pose>();
            if (f?.poses == null) return list;
            foreach (var p in f.poses) if (Matches(p, filter)) list.Add(p);
            return list;
        }

        public static string Norm(string s) => (s ?? "").Replace('_', '-').ToLowerInvariant();

        /// <summary>JsonUtility in Unity; System.Text.Json (public fields) in the plain .NET test host (tests/g3poses).</summary>
        static G3PoseFile Deserialize(string json)
        {
#if UNITY_5_3_OR_NEWER
            return UnityEngine.JsonUtility.FromJson<G3PoseFile>(json);
#else
            return System.Text.Json.JsonSerializer.Deserialize<G3PoseFile>(json, new System.Text.Json.JsonSerializerOptions { IncludeFields = true });
#endif
        }
    }
}
