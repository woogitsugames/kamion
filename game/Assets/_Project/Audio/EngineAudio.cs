using System;
using UnityEngine;
using UnityEngine.Audio;

namespace TruckSim.Audio
{
    /// <summary>Which recordings play the engine (ADR 0137): procedural synthesis (ADR 0007) or the ElevenLabs layers.</summary>
    public enum EngineSoundSource { Procedural = 0, ElevenLabs = 1 }

    /// <summary>
    /// Engine sound controller for the player truck: rpm x load loop grids (exterior + cab),
    /// engine-brake layer, turbo whistle and lift-off sigh, all driven by <see cref="IEngineAudioState"/>.
    ///
    /// Place on the engine-bay transform of the tractor (exterior voices are 3D at this point;
    /// cab banks should have spatialBlend = 0). Set <see cref="InteriorBlend"/> from the camera
    /// system (1 = cab camera, 0 = outside).
    ///
    /// Per-frame cost: a handful of float ops + at most ~10 AudioSource property writes.
    /// No allocations after Awake. Mix constants mirror tools/audio/render_demo.py (MIX, TAU).
    /// </summary>
    [DisallowMultipleComponent]
    public sealed class EngineAudio : MonoBehaviour
    {
        [Serializable]
        public struct PerspectiveMix
        {
            [Range(0f, 2f)] public float engine;
            [Range(0f, 2f)] public float engineBrake;
            [Range(0f, 1f)] public float turbo;
            [Range(0f, 1f)] public float turboLiftoff;

            public static PerspectiveMix Exterior => new PerspectiveMix { engine = 1f, engineBrake = 1f, turbo = 0.11f, turboLiftoff = 0.30f };
            public static PerspectiveMix Cab => new PerspectiveMix { engine = 1f, engineBrake = 0.85f, turbo = 0.045f, turboLiftoff = 0.10f };
        }

        [Header("Input")]
        [Tooltip("Component implementing IEngineAudioState (powertrain or EngineAudioDebugState). Optional if SetInput() is used.")]
        [SerializeField] MonoBehaviour stateProvider;

        [Header("Banks (generated by tools/audio)")]
        [SerializeField] EngineSoundBank exteriorEngine;
        [SerializeField] EngineSoundBank cabEngine;
        [SerializeField] EngineSoundBank exteriorEngineBrake;
        [SerializeField] EngineSoundBank cabEngineBrake;
        [SerializeField] AudioClip turboWhistleLoop;
        [SerializeField] AudioClip turboLiftoff;
        [SerializeField] AudioClip turboLiftoffCab;
        [SerializeField] AudioMixerGroup output;

        [Header("ElevenLabs events (ADR 0137; null in the procedural set)")]
        [SerializeField] AudioClip startExt;
        [SerializeField] AudioClip startCab, stopExt, stopCab, clatterExt, clatterCab;
        [Tooltip("WORKING_VALUE (owner listening test): start/stop one-shot level, idle clatter level.")]
        [SerializeField, Range(0f, 1f)] float startStopVolume = 1f;
        [SerializeField, Range(0f, 1f)] float clatterVolume = 0.6f;
        [Tooltip("Engine loops stay silent this long after a start (the start clip carries crank + catch), then fade in [s].")]
        [SerializeField] float startLoopDelay = 1.2f;
        [SerializeField] float startLoopFade = 1.0f;

        [Header("Turbo v2 (ADR 0142, ElevenLabs set; null = v1 whistle)")]
        [SerializeField] AudioClip turboWhineExt;
        [SerializeField] AudioClip turboWhineCab, turboRushExt, turboRushCab;
        [Tooltip("WORKING_VALUE: v2 layer gains outside / in the cab (the cabin clips are already firewall-filtered, -15 dB).")]
        [SerializeField] float turboWhineExtMix = 0.10f, turboRushExtMix = 0.18f, turboWhineCabMix = 0.20f, turboRushCabMix = 0.30f;
        [Tooltip("Whine pitch at zero boost / added at full boost (v2 loop rendered at 2.6 kHz). Turbo shaft idles at ~half speed.")]
        [SerializeField] float turboWhinePitchBase = 0.55f, turboWhinePitchRange = 0.9f;

        [Header("Mix")]
        [SerializeField, Range(0f, 1f)] float interiorBlend = 1f;
        [SerializeField] PerspectiveMix exteriorMix = PerspectiveMix.Exterior;
        [SerializeField] PerspectiveMix cabMix = PerspectiveMix.Cab;
        [SerializeField, Range(0.5f, 1f)] float crossfadeCoherence = 0.9f;

        [Header("Smoothing time constants [s]")]
        [SerializeField] float rpmTau = 0.035f;
        [SerializeField] float loadTau = 0.05f;
        [SerializeField] float engineBrakeTau = 0.08f;
        [SerializeField] float boostTau = 0.05f;

        [Header("Turbo")]
        [Tooltip("Whistle pitch at zero boost / added at full boost (loop is rendered at 3.2 kHz).")]
        [SerializeField] float turboPitchBase = 0.6f;
        [SerializeField] float turboPitchRange = 0.85f;
        [SerializeField] float liftoffMinBoost = 0.35f;
        [SerializeField] float liftoffCooldown = 1f;

        EngineLayerGrid _extEngine, _cabEngine, _extBrake, _cabBrake;
        PerspectiveLoop _turboWhine, _turboRush;
        AudioSource _turbo, _oneShot, _events;
        PerspectiveLoop _clatter;
        bool _running, _hasEvents;
        float _startHold, _runGate = 1f;
        IEngineAudioState _state;
        EngineAudioInput _pushed;
        bool _hasPushed;
        float _rpm, _load, _brake, _boost, _throttle;
        float _throttleHold, _liftoffTimer;
        bool _initialised, _primed;

        /// <summary>1 = cab perspective, 0 = exterior. Equal-power blend between the two banks.</summary>
        public float InteriorBlend
        {
            get => interiorBlend;
            set => interiorBlend = Mathf.Clamp01(value);
        }

        /// <summary>
        /// Extra gain of the cabin engine and engine-brake banks (ADR 0142: the cab mix of the ElevenLabs set puts the engine
        /// ~3 dB lower so tyres and wind are heard at cruise). 1 = unchanged.
        /// </summary>
        public float CabEngineScale { get; set; } = 1f;

        /// <summary>Turbo v2 layers in use (ElevenLabs set).</summary>
        public bool TurboV2 => _turboWhine != null;
        /// <summary>Current whine / rush output gain (before the perspective split). For tests.</summary>
        public float TurboWhineGain { get; private set; }
        public float TurboRushGain { get; private set; }

        /// <summary>Set the banks come from (<see cref="Configure"/>).</summary>
        public EngineSoundSource Source { get; private set; }

        /// <summary>0..1 gate of the engine loops around start/stop events (1 = normal running). For tests.</summary>
        public float RunGate => _runGate;

        /// <summary>Engine start / stop one-shots played since the component was configured. For tests.</summary>
        public int StartEvents { get; private set; }
        public int StopEvents { get; private set; }

        public int ActiveEngineVoices =>
            (_extEngine?.ActiveVoices ?? 0) + (_cabEngine?.ActiveVoices ?? 0) +
            (_extBrake?.ActiveVoices ?? 0) + (_cabBrake?.ActiveVoices ?? 0);

        /// <summary>Push-style input (overrides stateProvider for this frame).</summary>
        public void SetInput(in EngineAudioInput input)
        {
            _pushed = input;
            _hasPushed = true;
        }

        /// <summary>
        /// Runtime wiring (banks from <see cref="VehicleAudioLibrary"/>). Call on an inactive GameObject before it is
        /// activated, or later: an already initialised component rebuilds its voice pools (allocates, not per frame).
        /// </summary>
        public void Configure(VehicleAudioLibrary lib, MonoBehaviour provider = null,
                              EngineSoundSource source = EngineSoundSource.Procedural)
        {
            if (source == EngineSoundSource.ElevenLabs && !lib.HasElevenLabs) source = EngineSoundSource.Procedural;
            Source = source;
            turboWhistleLoop = lib.turboWhistleLoop; // physics-driven whistle stays procedural in both sets (ADR 0137)
            if (source == EngineSoundSource.ElevenLabs)
            {
                exteriorEngine = lib.elExteriorEngine; cabEngine = lib.elCabEngine;
                exteriorEngineBrake = lib.elExteriorEngineBrake != null ? lib.elExteriorEngineBrake : lib.exteriorEngineBrake;
                cabEngineBrake = lib.elCabEngineBrake != null ? lib.elCabEngineBrake : lib.cabEngineBrake;
                turboLiftoff = lib.elTurboWastegate.IsValid ? lib.elTurboWastegate.ext : lib.turboLiftoff;
                turboLiftoffCab = lib.elTurboWastegate.IsValid ? lib.elTurboWastegate.cab : null;
                startExt = lib.elEngineStart.ext; startCab = lib.elEngineStart.cab;
                stopExt = lib.elEngineStop.ext; stopCab = lib.elEngineStop.cab;
                clatterExt = lib.elIdleClatter.ext; clatterCab = lib.elIdleClatter.cab;
                turboWhineExt = lib.elTurboWhine.ext; turboWhineCab = lib.elTurboWhine.cab;
                turboRushExt = lib.elTurboRush.ext; turboRushCab = lib.elTurboRush.cab;
            }
            else
            {
                exteriorEngine = lib.exteriorEngine; cabEngine = lib.cabEngine;
                exteriorEngineBrake = lib.exteriorEngineBrake; cabEngineBrake = lib.cabEngineBrake;
                turboLiftoff = lib.turboLiftoff; turboLiftoffCab = null;
                startExt = startCab = stopExt = stopCab = clatterExt = clatterCab = null;
                turboWhineExt = turboWhineCab = turboRushExt = turboRushCab = null;
            }
            if (provider != null) stateProvider = provider;
            if (!_initialised) return;
            OnDisable();
            for (int i = transform.childCount - 1; i >= 0; i--) Destroy(transform.GetChild(i).gameObject);
            Awake();
        }

        void Awake()
        {
            _state = stateProvider as IEngineAudioState;
            if (stateProvider != null && _state == null)
                Debug.LogError("EngineAudio: stateProvider does not implement IEngineAudioState", this);

            _extEngine = MakeGrid(exteriorEngine, 6, 0x1234u, "engExt");
            _cabEngine = MakeGrid(cabEngine, 6, 0x2345u, "engCab");
            _extBrake = MakeGrid(exteriorEngineBrake, 3, 0x3456u, "brkExt");
            _cabBrake = MakeGrid(cabEngineBrake, 3, 0x4567u, "brkCab");

            _turbo = MakeSource("turbo", turboWhistleLoop, true, exteriorEngine != null ? exteriorEngine.spatialBlend : 1f);
            _oneShot = MakeSource("turboLiftoff", null, false, 0f);
            _events = MakeSource("engineEvents", null, false, 0f);
            _hasEvents = startExt != null || stopExt != null;
            _clatter = clatterExt != null
                ? new PerspectiveLoop(transform, "idleClatter", clatterExt, clatterCab, Vector3.zero, 40, 1f)
                : null;
            bool v2 = turboWhineExt != null && turboRushExt != null;
            _turboWhine = v2 ? new PerspectiveLoop(transform, "turboWhine", turboWhineExt, turboWhineCab, Vector3.zero, 36, 1f) : null;
            _turboRush = v2 ? new PerspectiveLoop(transform, "turboRush", turboRushExt, turboRushCab, Vector3.zero, 36, 1f) : null;
            _runGate = 1f;
            _startHold = 0f;
            StartEvents = StopEvents = 0;
            _initialised = true;
        }

        EngineLayerGrid MakeGrid(EngineSoundBank bank, int pool, uint seed, string label)
        {
            if (bank == null) return null;
            if (!bank.Validate(out string err))
            {
                Debug.LogError("EngineAudio: " + err, this);
                return null;
            }
            return new EngineLayerGrid(bank, transform, pool, output, seed, label);
        }

        AudioSource MakeSource(string label, AudioClip clip, bool loop, float spatial)
        {
            var go = new GameObject(label);
            go.transform.SetParent(transform, false);
            var s = go.AddComponent<AudioSource>();
            s.playOnAwake = false;
            s.loop = loop;
            s.clip = clip;
            s.volume = 0f;
            s.priority = 32;
            s.spatialBlend = spatial;
            s.dopplerLevel = 0f;
            s.outputAudioMixerGroup = output;
            return s;
        }

        void OnDisable()
        {
            if (!_initialised) return;
            _extEngine?.StopAll();
            _cabEngine?.StopAll();
            _extBrake?.StopAll();
            _cabBrake?.StopAll();
            if (_turbo != null) _turbo.Stop();
            _clatter?.Set(0f, 1f, interiorBlend);
            _turboWhine?.Set(0f, 1f, interiorBlend);
            _turboRush?.Set(0f, 1f, interiorBlend);
            _primed = false;
        }

        static float Smooth(float current, float target, float tau, float dt)
        {
            return tau <= 0f ? target : current + (target - current) * (1f - Mathf.Exp(-dt / tau));
        }

        void Update()
        {
            EngineAudioInput x;
            if (_hasPushed) { x = _pushed; _hasPushed = false; }
            else if (_state != null) x = EngineAudioInput.From(_state);
            else return;

            float dt = Time.deltaTime;
            if (!_primed)
            {
                _rpm = x.Rpm; _load = x.Load; _brake = x.EngineBrake; _boost = x.TurboBoost;
                _running = x.Rpm > StartRpm; // already running at spawn: no start one-shot
                _primed = true;
            }
            else UpdateEvents(x.Rpm, dt);
            _rpm = Smooth(_rpm, Mathf.Max(0f, x.Rpm), rpmTau, dt);
            _load = Smooth(_load, Mathf.Clamp01(x.Load), loadTau, dt);
            _brake = Smooth(_brake, Mathf.Clamp01(x.EngineBrake), engineBrakeTau, dt);
            _boost = Smooth(_boost, Mathf.Clamp01(x.TurboBoost), boostTau, dt);
            _throttle = Mathf.Clamp01(x.Throttle);

            // perspective blend (different banks are incoherent -> equal power)
            float b = interiorBlend * Mathf.PI * 0.5f;
            float extW = Mathf.Cos(b), cabW = Mathf.Sin(b);
            // fades the loops out while the engine stalls / is switched off; _runGate adds the start/stop gating (ADR 0137)
            float runGain = Mathf.Clamp01((_rpm - 80f) / 300f) * _runGate;

            Tick(_extEngine, exteriorMix.engine * extW * runGain, _load, dt);
            Tick(_cabEngine, cabMix.engine * CabEngineScale * cabW * runGain, _load, dt);
            Tick(_extBrake, exteriorMix.engineBrake * extW * _brake * runGain, 0f, dt);
            Tick(_cabBrake, cabMix.engineBrake * CabEngineScale * cabW * _brake * runGain, 0f, dt);

            if (_turboWhine != null) UpdateTurboV2(runGain);
            UpdateTurbo(extW, cabW, dt);

            if (_clatter != null)
            {
                // injector / valve-train clatter: audible at idle, masked by combustion above ~1300 rpm
                float idle = 1f - Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(700f, 1300f, _rpm));
                _clatter.Set(clatterVolume * runGain * idle * (0.75f + 0.25f * _load), Mathf.Clamp(_rpm / 600f, 0.7f, 2f), interiorBlend);
            }
        }

        const float StartRpm = 400f, StopRpm = 250f;

        /// <summary>
        /// Start / stop from the rpm (the physics restarts a stalled engine by jumping to idle, Engine.Restart; a stall
        /// drops below the stall speed). With event clips (ElevenLabs) the loops are gated: silent while the start clip
        /// cranks, faded in after <see cref="startLoopDelay"/>, cut in 0.2 s when the engine stops (the stop clip carries
        /// the run-down). Procedural set: no clips, gate stays 1 (unchanged ADR 0007 behaviour).
        /// </summary>
        void UpdateEvents(float rpm, float dt)
        {
            if (!_running && rpm > StartRpm)
            {
                _running = true;
                if (_hasEvents && startExt != null)
                {
                    PlayEvent(startExt, startCab);
                    _startHold = startLoopDelay + startLoopFade;
                    _runGate = 0f;
                    StartEvents++;
                }
            }
            else if (_running && rpm < StopRpm)
            {
                _running = false;
                if (_hasEvents && stopExt != null) { PlayEvent(stopExt, stopCab); StopEvents++; }
            }
            if (!_hasEvents) { _runGate = 1f; return; }
            _startHold = Mathf.Max(0f, _startHold - dt);
            float target = _running ? 1f - Mathf.Clamp01(_startHold / Mathf.Max(1e-3f, startLoopFade)) : 0f;
            _runGate = target >= _runGate ? target : Mathf.MoveTowards(_runGate, target, dt / 0.2f);
        }

        void PlayEvent(AudioClip ext, AudioClip cab)
        {
            bool cabView = interiorBlend > 0.5f;
            var clip = cabView && cab != null ? cab : ext;
            _events.spatialBlend = cabView ? 0f : (exteriorEngine != null ? exteriorEngine.spatialBlend : 1f);
            _events.PlayOneShot(clip, startStopVolume);
        }

        void Tick(EngineLayerGrid g, float gain, float load, float dt)
        {
            if (g == null) return;
            g.Coherence = g.Incoherent ? 0f : crossfadeCoherence;
            g.Tick(_rpm, load, gain, dt);
        }

        /// <summary>
        /// Turbo v2 (ADR 0142). Whine: shaft speed follows boost (physics first-order lag, Engine.Boost), gain ~boost^1.5
        /// and opens with the throttle (compressor loading). Rush: mass flow ~ boost x rpm, audible as an airy intake hiss
        /// that also follows rpm off boost. Cabin clips are prerendered through the firewall filter, the mix factors only
        /// set the balance. Pitch mapping and gains are WORKING_VALUE (owner listening test).
        /// </summary>
        void UpdateTurboV2(float runGain)
        {
            float rpmN = Mathf.Clamp01((_rpm - 600f) / 1500f);
            TurboWhineGain = runGain * Mathf.Pow(_boost, 1.5f) * (0.35f + 0.65f * _throttle);
            TurboRushGain = runGain * (0.15f * rpmN + 0.85f * Mathf.Pow(_boost, 1.2f) * (0.4f + 0.6f * rpmN)) * (0.5f + 0.5f * _throttle);
            _turboWhine.SetMix(turboWhineExtMix, turboWhineCabMix);
            _turboRush.SetMix(turboRushExtMix, turboRushCabMix);
            _turboWhine.Set(TurboWhineGain, turboWhinePitchBase + turboWhinePitchRange * _boost, interiorBlend);
            _turboRush.Set(TurboRushGain, 0.85f + 0.3f * _boost + 0.1f * rpmN, interiorBlend);
        }

        void UpdateTurbo(float extW, float cabW, float dt)
        {
            if (_turbo == null || turboWhistleLoop == null) return;
            float mixT = exteriorMix.turbo * extW + cabMix.turbo * cabW;
            float vol = _turboWhine != null ? 0f : mixT * Mathf.Pow(_boost, 1.5f) * (0.35f + 0.65f * _throttle);
            if (vol > 1e-4f)
            {
                if (!_turbo.isPlaying) _turbo.Play();
                _turbo.volume = vol;
                _turbo.pitch = turboPitchBase + turboPitchRange * _boost;
            }
            else if (_turbo.isPlaying)
            {
                _turbo.volume = 0f;
                _turbo.Stop();
            }

            // lift-off: throttle peak-hold vs current; fires once per lift at sufficient boost
            _throttleHold = Mathf.Max(_throttle, _throttleHold - 2f * dt);
            _liftoffTimer = Mathf.Max(0f, _liftoffTimer - dt);
            if (turboLiftoff != null && _liftoffTimer <= 0f && _throttleHold - _throttle > 0.5f && _boost > liftoffMinBoost)
            {
                float mixL = exteriorMix.turboLiftoff * extW + cabMix.turboLiftoff * cabW;
                var clip = interiorBlend > 0.5f && turboLiftoffCab != null ? turboLiftoffCab : turboLiftoff;
                _oneShot.PlayOneShot(clip, mixL * _boost);
                _liftoffTimer = liftoffCooldown;
            }
        }
    }
}
