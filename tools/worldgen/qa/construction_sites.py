"""ADR 0214: write the `construction_site` override of a region from the OSM construction axes.

Reads the pinned OSM extract (Data/raw/osm/podlaskie-261108.osm.pbf), takes every way tagged `highway=construction`
(and the extra ways named with --ways, e.g. a mapped carriageway that is not open yet, owner D65 p.6) that comes within
the tile bbox + margin, clips it to the bbox grown by its half-width + 10 m (both tiles of a seam get the same corridor
edge) and writes one override block between marker comments into Data/Regions/<id>/overrides.yaml (replaced on a re-run,
the rest of the file untouched). The coordinates are copied, so the site survives later OSM edits (authored override).

  uv run --project tools/worldgen python tools/worldgen/qa/construction_sites.py --region dk65-06 [--ways 1557884361,...]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import osmium
from pyproj import Transformer
from shapely.geometry import LineString, box

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools/worldgen"))
import regions  # noqa: E402

PBF = ROOT / "Data/raw/osm/podlaskie-261108.osm.pbf"
# half-width of the stripped corridor by the class under construction, metres (WORKING_VALUE: knyszyn-s ADR 0204 used
# 30 m for the expressway; owner frames 2026-07-27/28 show sand from the verge of DK65 to the forest edge)
HALF_W = {"motorway": 30.0, "trunk": 30.0, "motorway_link": 12.0, "trunk_link": 12.0, "primary": 10.0,
          "secondary": 10.0, "tertiary": 7.0, "unclassified": 7.0, "service": 5.0}
EXTRA_HALF_W = 10.0
BEGIN = "  # BEGIN construction_site (generated by tools/worldgen/qa/construction_sites.py, ADR 0214; do not edit by hand)"
END = "  # END construction_site"


def collect(bb, extra):
    tr = Transformer.from_crs("EPSG:4326", "EPSG:2180", always_xy=True)
    x0, y0, x1, y1 = bb
    out = []

    class H(osmium.SimpleHandler):
        def way(self, w):
            tg = dict(w.tags)
            cls = tg.get("construction") if tg.get("highway") == "construction" else None
            if cls is None and w.id not in extra:
                return
            try:
                pts = [tr.transform(n.lon, n.lat) for n in w.nodes]
            except osmium.InvalidLocationError:
                return
            hw = EXTRA_HALF_W if w.id in extra else HALF_W.get(cls or "", 7.0)
            m = hw + 10.0
            line = LineString(pts).intersection(box(x0 - m, y0 - m, x1 + m, y1 + m))
            if line.is_empty or line.length < 1.0:
                return
            for part in getattr(line, "geoms", [line]):
                if part.geom_type != "LineString" or part.length < 1.0:
                    continue
                out.append({"osm_way": w.id, "class": "not_open" if w.id in extra else (cls or "?"),
                            "edited": str(w.timestamp)[:10], "half_width_m": hw,
                            "line": [[round(x, 1), round(y, 1)] for x, y in part.simplify(0.3).coords]})

    H().apply_file(str(PBF), locations=True)
    return sorted(out, key=lambda a: (a["osm_way"], a["line"][0]))


def block(rid, axes, fence_share, heaps):
    L = [BEGIN,
         f"  - id: {rid}-s19-construction",
         "    kind: construction_site",
         "    reason: >-",
         "      Owner D64/D65 p.4: the S19 works beside DK65 (km 16.7-25) stay beside the open old road; site simplified.",
         "      Corridor = OSM highway=construction axes (podlaskie-261108, edits 2026-05..09) buffered by the class",
         "      half-width, minus 4 m off every built road; sand ground, seeded spoil heaps, temporary mesh fence on part",
         "      of the edge facing the road (owner frames 20260727_073424/073802, 20260728_104740: sand platforms and heaps",
         "      from the verge to the forest edge, a mesh fence on one frame). Platform 0 m: the NMT 2025 already holds the",
         "      earthworks of 2025. Machines, temporary signs and yellow markings not modelled. All sizes WORKING_VALUE.",
         "    confidence: low",
         "    verify: owner drive - which side, how far from the verge, fences",
         "    platform_m: 0.0",
         f"    heaps_per_ha: {heaps}",
         f"    fence: {{share: {fence_share}}}",
         "    axes:"]
    for a in axes:
        pts = ", ".join(f"[{x}, {y}]" for x, y in a["line"])
        L.append(f"      - {{osm_way: {a['osm_way']}, class: {a['class']}, edited: '{a['edited']}', "
                 f"half_width_m: {a['half_width_m']}, line_epsg2180: [{pts}]}}")
    L.append(END)
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--region", required=True)
    ap.add_argument("--ways", default="", help="extra OSM way ids (mapped road not open yet) to turn into the site")
    ap.add_argument("--fence-share", type=float, default=0.2)
    ap.add_argument("--heaps-per-ha", type=float, default=1.2)
    a = ap.parse_args()
    reg = regions.get(a.region)
    extra = {int(x) for x in a.ways.split(",") if x.strip()}
    axes = collect(reg.bbox, extra)
    p = ROOT / "Data/Regions" / a.region / "overrides.yaml"
    text = p.read_text(encoding="utf-8") if p.exists() else (
        f"# Authored overrides of region {a.region} (ADR 0214). Every entry survives a re-import.\noverrides:\n")
    if BEGIN in text:
        i, j = text.index(BEGIN), text.index(END) + len(END) + 1
        text = text[:i] + text[j:]
    if not text.endswith("\n"):
        text += "\n"
    if axes:
        text += block(a.region, axes, a.fence_share, a.heaps_per_ha)
    p.write_text(text, encoding="utf-8", newline="\n")
    print(a.region, len(axes), "axes", sorted({x["osm_way"] for x in axes}))


if __name__ == "__main__":
    main()
