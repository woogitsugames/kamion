"""Driver-eye place cameras of the DK19 route tiles (ADR 0278 tiles 5-7, owner D81) -> control_cameras_place.authored.json.

Positions are taken from route_start.json (centre of the rightmost lane of the control route, scripts/export-route.py):
a camera `back_m` before the first route point on a named street / way, looking along the route. Re-run after
export-route.py; the file is an authored override read by build_world (ADR 0196/0208).

  uv run --project tools/worldgen python tools/worldgen/qa/dk19_place_cameras.py [--write]
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import regions  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
# (camera id, street name of the graph edge the camera looks at, metres before its first route point, note)
SPEC = {
    "bialystok-bojary": [
        ("dk19_sosabowskiego", "Generała Stanisława Sosabowskiego", -150.0, "Sosabowskiego southbound 150 m after its start (DK19/DK65)"),
        ("dk19_piastowska_n", "Piastowska", -120.0, "Piastowska southbound 120 m after the turn from Sosabowskiego (70 km/h section, measured 8.0 m carriageway)"),
        ("dk19_piastowska_seam_s", "__end__", 70.0, "Piastowska southbound 70 m before the south seam with bialystok-mickiewicza (widening 8.0 -> 14.0 m must end flush on the tile edge)"),
    ],
    "bialystok-mickiewicza": [
        ("dk19_piastowska_seam_n", "__start__", -6.0, "Piastowska southbound 6 m inside the north seam with bialystok-bojary (view of a truck arriving from Bojary: 4-lane approach)"),
        ("dk19_pl_antonowicza", "Plac Witolda Antonowicza", 60.0, "Piastowska southbound 60 m before pl. Antonowicza (left/through lanes; Branickiego NW = 8 t)"),
        ("dk19_branickiego", "Jana Klemensa Branickiego", -200.0, "Branickiego towards rondo Meyera, 200 m after pl. Antonowicza (measured 8.0 m carriageway)"),
        ("dk19_rondo_meyera", "Rondo Andrzeja Bronisława Meyera", 70.0, "approach to rondo Meyera 70 m before the ring (straight on = Nowowarszawska 3.5 t; the route turns into Ciolkowskiego)"),
        ("dw678_ciolkowskiego", "Konstantego Ciołkowskiego", -150.0, "Ciolkowskiego 150 m after rondo Meyera (DW678, measured 8.0 m carriageway)"),
        ("dw678_seam_dojlidy", "__end__", 60.0, "Ciolkowskiego 60 m before the south seam with bialystok-dojlidy (7.0 m of the locked neighbour on the seam)"),
    ],
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    for rid, spec in SPEC.items():
        d = REPO / "Data" / "Regions" / rid
        rt = json.loads((d / "route_start.json").read_text(encoding="utf-8"))
        g = json.loads((d / "roads.graph.json").read_text(encoding="utf-8"))
        name = {e["id"]: (e["attrs"].get("name") or {}).get("v") for e in g["edges"]}
        P, E, step = rt["points_en"], rt["edge"], rt["step_m"]
        cams = []
        for cid, street, back, note in spec:
            if street == "__start__":
                i0 = 0
            elif street == "__end__":
                i0 = len(P) - 1
            else:
                i0 = next(i for i, e in enumerate(E) if name.get(e) == street)
            i = min(max(i0 - int(round(back / step)), 0), len(P) - 6)
            (x0, y0), (x1, y1) = P[i], P[i + 5]
            hd = math.degrees(math.atan2(x1 - x0, y1 - y0)) % 360.0
            cams.append({"id": cid, "pos_en": [round(x0, 1), round(y0, 1)], "heading_deg": round(hd, 1), "eye_m": 2.5,
                         "fov_deg": 60.0, "pitch_deg": 0.0, "note": f"{note}; route s = {i * step:.0f} m"})
            print(rid, cams[-1])
        r = regions.get(rid)
        out = {"schema": "truck-sim-pl/place-cameras/1",
               "provenance": (f"authored_override (ADR 0278, owner D81; mechanism of ADR 0196/0208): driver-eye control cameras at the named "
                              f"places of the truck route C <-> Dojlidy. Position region-local E/N (origin {r.origin[0]:.0f}, {r.origin[1]:.0f}) "
                              f"from route_start.json (centre of the rightmost lane), height = terrain (NMT) + eye_m, heading_deg compass, "
                              f"fov_deg vertical. Generated by tools/worldgen/qa/dk19_place_cameras.py."),
               "cameras": cams}
        if a.write:
            (d / "control_cameras_place.authored.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
