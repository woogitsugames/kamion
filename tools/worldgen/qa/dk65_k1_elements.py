"""ADR 0220: DK65 cross-section elements of research K1 (dk65-01 ... dk65-05) -> authored overrides.

    uv run --project tools/worldgen python tools/worldgen/qa/dk65_k1_elements.py [--check]

Input: `docs/reports/map/dk65_k1_elements.json` - elements in route chainage (km trasy of the ADR 0203 plan, side L / P
of the direction of growing km, roads.route_km), each with its evidence (K1 manifest row, orthophoto strip of ADR 0220).
Output: one generated block per tile at the end of `Data/Regions/<tile>/overrides.yaml`, between the markers below
(replaced on every run, the rest of the file is untouched; hand edits belong outside the block):
  * `edge_line_spacing` on the route ways of the tile that carry override edge lines (way-level, same value in every
    tile that shares a way -> no step on the seams);
  * `kind: edge_line_dashed` - broken spans of the edge line (line_en = the axis at km_from / km_to, region-local);
  * `kind: paved_area` - the asphalt of a bus bay outside the carriageway (polygon_epsg2180, material yard_asphalt).
--check: exit 1 if a block differs from what the table gives (test / CI).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from roads.route_km import RouteKm, km_to_region, region_origin, tile_of_km  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
TABLE = REPO / "docs" / "reports" / "map" / "dk65_k1_elements.json"
BEGIN = "  # >>> ADR 0220 generated by tools/worldgen/qa/dk65_k1_elements.py from docs/reports/map/dk65_k1_elements.json"
END = "  # <<< ADR 0220"
SIDE = {"L": "left", "P": "right"}


def _q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def bay_polygon(route: RouteKm, el: dict, step_m: float = 2.0):
    """EPSG:2180 ring of a bus bay: from `inner_m` (lateral, the carriageway edge) to `inner_m + depth_m`, full depth
    between km_from + taper_in and km_to - taper_out, linear tapers to zero depth at km_from / km_to."""
    a, b = el["km"]
    tin, tout = el.get("taper_m", [15.0, 15.0])
    inner, depth = float(el["inner_m"]), float(el["depth_m"])
    s = np.arange(a * 1000.0, b * 1000.0 + 1e-6, step_m)
    if s[-1] < b * 1000.0 - 1e-6:
        s = np.append(s, b * 1000.0)
    d = np.minimum(np.clip((s - a * 1000.0) / max(tin, 1e-6), 0, 1), np.clip((b * 1000.0 - s) / max(tout, 1e-6), 0, 1))
    outer = [route.point(v / 1000.0, el["side"], inner + depth * f) for v, f in zip(s, d)]
    inner_pts = [route.point(v / 1000.0, el["side"], inner - 0.3) for v in s[::-1]]   # 0.3 m under the road edge
    return [[round(x, 2), round(y, 2)] for x, y in outer + inner_pts]


def block(tile: str, table: dict, route: RouteKm) -> list[str]:
    ox, oy, _ = region_origin(tile)
    out = [BEGIN, "  # Do not edit by hand: change the table and re-run the script (ADR 0220)."]
    sp = table["edge_line_spacing"]
    ways = sp["ways"].get(tile) or []
    if ways:
        out += [f"  - id: dk65-k1-edge-line-spacing",
                f"    target: {{osm_way: [{', '.join(str(w) for w in ways)}]}}",
                f"    reason: {_q(sp['reason'])}",
                f"    source: {_q(sp['source'])}",
                f"    confidence: {sp['confidence']}",
                f"    verify: {sp['verify']}",
                f"    set: {{edge_line_spacing: {sp['value']}}}"]
    for el in table["dashed"]:
        if el["tile"] != tile:
            continue
        a = km_to_region(tile, el["km"][0], route=route)
        b = km_to_region(tile, el["km"][1], route=route)
        out += [f"  - id: {el['id']}",
                f"    kind: edge_line_dashed",
                f"    line_en: [[{a['x']:.2f}, {a['z']:.2f}], [{b['x']:.2f}, {b['z']:.2f}]]   # km {el['km'][0]:.3f} -> {el['km'][1]:.3f}",
                f"    side: {SIDE[el['side']]}   # K1 {el['side']}",
                f"    dash_m: [{el['dash_m'][0]}, {el['dash_m'][1]}]",
                f"    reason: {_q(el['reason'])}",
                f"    source: {_q(el['source'])}",
                f"    confidence: {el['confidence']}",
                f"    verify: {el.get('verify', 'owner drive / owner photo')}"]
    for el in table["bays"]:
        if el["tile"] != tile:
            continue
        ring = bay_polygon(route, el)
        txt = ", ".join(f"[{x}, {y}]" for x, y in ring)
        out += [f"  - id: {el['id']}",
                f"    kind: paved_area",
                f"    material: yard_asphalt",
                f"    polygon_epsg2180: [{txt}]",
                f"    reason: {_q(el['reason'])}",
                f"    source: {_q(el['source'])}",
                f"    confidence: {el['confidence']}",
                f"    verify: {el.get('verify', 'owner drive / owner photo')}"]
    out.append(END)
    return out


def splice(text: str, blk: list[str]) -> str:
    lines = text.rstrip("\n").split("\n")
    if BEGIN in lines:
        i = lines.index(BEGIN)
        j = lines.index(END, i)
        lines = lines[:i] + lines[j + 1:]
        while lines and not lines[-1].strip():
            lines.pop()
    return "\n".join(lines + blk) + "\n"


def main():
    check = "--check" in sys.argv
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    route = RouteKm.from_plan()
    for el in table["dashed"] + table["bays"]:
        for km in el["km"]:
            t = tile_of_km(km)
            if t != el["tile"]:
                raise SystemExit(f"{el['id']}: km {km} lies in {t}, not in {el['tile']}")
    bad = []
    for tile in table["tiles"]:
        f = REPO / "Data" / "Regions" / tile / "overrides.yaml"
        new = splice(f.read_text(encoding="utf-8"), block(tile, table, route))
        if check:
            if new != f.read_text(encoding="utf-8"):
                bad.append(tile)
        else:
            f.write_text(new, encoding="utf-8")
            print(tile, "written")
    if bad:
        raise SystemExit(f"stale generated block: {bad}")


if __name__ == "__main__":
    main()
