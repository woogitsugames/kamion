"""Navigation trips across streamed tiles (ADR 0302).

Reads the streaming corridors (`Resources/WorldStreaming/route_links.json`, generated by
tools/worldgen/streaming/route_links.py, ADR 0285) and the control-route end points of the regions
(`Data/Regions/<id>/route_endpoints.json`, `end_epsg2180`), writes
`game/Assets/_Project/Gameplay/Resources/Nav/nav_trips.json` for the in-cab GPS:

  trips[]: id (= -route_to value), label (PL), tiles[], seam joins between consecutive tiles (EPSG:2180 point + side of
  the seam as seen from the `from` tile), goal point (EPSG:2180) = end of the last tile's control route (where the route
  autopilot stops), goal tile.

Trips:
  tykocin  corridor `bialystok-tykocin` (whole)
  s8       corridor `bialystok-s8`, cut at the first missing tile (the rest of the S8 loop is not built yet)
  monki    corridor `bialystok-tykocin` up to `knyszyn`, then `knyszyn-w` entered on DK65 (end of the link
           `knyszyn-dk65-to-dk65-w`) to the end of the knyszyn-w control route (DK65 towards Monki, ADR 0209)

Usage (from the repo root): uv run --no-project python tools/ui/build_nav_trips.py [--check]
--check: exit 1 when the committed file differs from a fresh build (test hook).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LINKS = ROOT / "game/Assets/_Project/World/Runtime/Streaming/Resources/WorldStreaming/route_links.json"
OUT = ROOT / "game/Assets/_Project/Gameplay/Resources/Nav/nav_trips.json"
REGIONS = ROOT / "Data/Regions"
SCHEMA = "truck-sim-pl/nav-trips/1"


def end_of_route(region: str) -> tuple[float, float]:
    p = REGIONS / region / "route_endpoints.json"
    d = json.loads(p.read_text(encoding="utf-8"))
    e = d["end_epsg2180"]
    return float(e[0]), float(e[1])


def corridor(links: dict, cid: str) -> dict:
    for c in links["corridors"]:
        if c["id"] == cid:
            return c
    raise SystemExit(f"corridor {cid} not in {LINKS}")


def link(links: dict, lid: str) -> dict:
    for l in links["links"]:
        if l["id"] == lid:
            return l
    raise SystemExit(f"link {lid} not in {LINKS}")


def joins_of(c: dict, tiles: list[str]) -> list[dict]:
    out = []
    for a, b in zip(tiles, tiles[1:]):
        j = next((j for j in c["joins"] if j["from"] == a and j["to"] == b), None)
        if j is None:
            raise SystemExit(f"no join {a} -> {b} in corridor {c['id']}")
        out.append({"from": a, "to": b, "side": j["side"], "x": round(j["x"], 3), "y": round(j["y"], 3)})
    return out


def trip(tid: str, label: str, tiles: list[str], joins: list[dict]) -> dict:
    gx, gy = end_of_route(tiles[-1])
    return {"id": tid, "label": label, "tiles": tiles, "joins": joins, "goalTile": tiles[-1],
            "goalX": round(gx, 3), "goalY": round(gy, 3)}


def build() -> dict:
    links = json.loads(LINKS.read_text(encoding="utf-8"))
    trips = []

    ty = corridor(links, "bialystok-tykocin")
    trips.append(trip("tykocin", "Tykocin", list(ty["tiles"]), joins_of(ty, ty["tiles"])))

    k = ty["tiles"].index("knyszyn")
    mt = list(ty["tiles"][: k + 1]) + ["knyszyn-w"]
    mj = joins_of(ty, ty["tiles"][: k + 1])
    lk = link(links, "knyszyn-dk65-to-dk65-w")
    mj.append({"from": "knyszyn", "to": "knyszyn-w", "side": "W", "x": round(lk["endX"], 3), "y": round(lk["endY"], 3)})
    trips.append(trip("monki", "Mońki (DK65)", mt, mj))

    s8 = corridor(links, "bialystok-s8")
    st = list(s8["tiles"])   # route_links.py keeps only the present prefix; "missing" lists the rest
    trips.append(trip("s8", "S8", st, joins_of(s8, st)))

    return {"schema": SCHEMA, "generator": "tools/ui/build_nav_trips.py", "frame": "EPSG:2180", "trips": trips}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(), ensure_ascii=False, indent=1) + "\n"
    if a.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print(f"{OUT} is stale: run tools/ui/build_nav_trips.py")
            return 1
        print("nav_trips.json fresh")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    d = json.loads(text)
    for t in d["trips"]:
        print(f"{t['id']}: {len(t['tiles'])} tiles, goal {t['goalTile']} ({t['goalX']}, {t['goalY']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
