"""dk19-tiles-s24: Codex review fixes of the D81 generators (ADR 0290).

(a) qa/dk19_xsec_overrides.py --write merges by id instead of replacing overrides.yaml (hand entries survive, the retired
    Piastowska seam profile 440321721 never comes back, re-running is byte-identical on the committed files);
(b) qa/dk19_route_vias.py treats a missing oneway tag as two-way, like qa/dk19_route_check.py;
(c) qa/dk19_route_vias.py drops stale via_epsg2180 / via_note when the new via list is empty.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools" / "worldgen"))
from tools.worldgen.qa import dk19_route_vias as RV  # noqa: E402
from tools.worldgen.qa import dk19_xsec_overrides as XO  # noqa: E402

HEAD = "# Authored overrides of region x\n# second comment line\noverrides:\n"


def _entry(i, body="    set: {width: 8.0}\n"):
    return f"  - id: {i}\n    target: {{osm_way: [1]}}\n{body}"


def test_merge_keeps_hand_entries_and_replaces_measured_in_place():
    text = HEAD + _entry("measured-a", "    set: {width: 7.0}\n") + _entry("hand-kerb", "    set: {left: kerb}\n")
    out = XO.merge(text, {"measured-a": _entry("measured-a", "    set: {width: 8.0}\n")}, {})
    assert out.startswith(HEAD)
    assert "set: {left: kerb}" in out                       # hand-written entry not generated by the script survives
    assert "set: {width: 8.0}" in out and "set: {width: 7.0}" not in out
    assert out.index("measured-a") < out.index("hand-kerb")  # order kept


def test_merge_seeds_only_when_absent_and_never_retired():
    seed_new = _entry("seam-seed", "    set: {width: 14.0}\n")
    text = HEAD + _entry("seam-seed", "    set: {width: 13.0}\n")  # the file already has it, edited by hand
    out = XO.merge(text, {}, {"seam-seed": seed_new})
    assert "width: 13.0" in out and "width: 14.0" not in out
    retired = next(iter(XO.RETIRED))
    out2 = XO.merge(HEAD + _entry(retired), {}, {retired: _entry(retired)})
    assert retired not in out2


def test_merge_appends_new_and_fills_an_empty_list():
    out = XO.merge("# c\noverrides: []\n", {"m": _entry("m")}, {"s": _entry("s")})
    assert out.startswith("# c\noverrides:\n") and "[]" not in out
    assert out.index("  - id: s") < out.index("  - id: m")


def test_merge_is_identity_on_the_committed_dk19_overrides():
    measured = XO.entries(seams=False)
    for tile in ("bialystok-bojary", "bialystok-mickiewicza"):
        text = (ROOT / "Data" / "Regions" / tile / "overrides.yaml").read_text(encoding="utf-8")
        out = XO.merge(text, XO.by_id(measured.get(tile, [])), XO.by_id(XO.SEAM.get(tile, [])))
        assert out == text, tile
    mick = (ROOT / "Data" / "Regions" / "bialystok-mickiewicza" / "overrides.yaml").read_text(encoding="utf-8")
    assert "dk19-ciolkowskiego-seam-dojlidy-left-kerb" in mick
    assert "440321721]" not in (ROOT / "Data" / "Regions" / "bialystok-bojary" / "overrides.yaml").read_text(encoding="utf-8")


def test_oneway_directions_match_route_check():
    assert RV.directions(None) == (True, True)               # missing tag = two-way (Codex review s24)
    assert RV.directions("no") == (True, True)
    assert RV.directions("yes") == (True, False)
    assert RV.directions("-1") == (False, True)


def test_empty_via_clears_stale_points():
    j = {"via_epsg2180": [[1.0, 2.0]], "via_note": "old", "keep": 1}
    out = RV.apply_endpoints(dict(j), (0.0, 0.0), (5.0, 5.0), [], 12.34)
    assert "via_epsg2180" not in out and "via_note" not in out and out["keep"] == 1
    assert out["start_epsg2180"] == [0.0, 0.0] and out["end_epsg2180"] == [5.0, 5.0] and out["length_truck_route_m"] == 12.3
    out2 = RV.apply_endpoints({}, (0.0, 0.0), (5.0, 5.0), [[3.0, 3.0]], 10.0)
    assert out2["via_epsg2180"] == [[3.0, 3.0]] and "via_note" in out2
