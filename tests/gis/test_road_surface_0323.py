"""ADR 0323 (critic wave 6 pkt 2.1-2.4): stone carriageways get real sets, sealed cracks and pavement condition are
generated by rule, a compact roundabout plate carries no arm-axis wheel paths, barriers are matt zinc."""
import json
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import pytest

from roads import decals as DC
from roads import network as NW
from roads.geom import Polyline

REPO = Path(__file__).resolve().parents[2]


class _Buf:
    def __init__(self):
        self.parts = []

    def add(self, layer, mat, V, UV, T, src=None, UV1=None, **kw):
        self.parts.append(SimpleNamespace(layer=layer, mat=mat, V=np.asarray(V, float), UV=np.asarray(UV, float),
                                          T=np.asarray(T, int), src=src, UV1=np.asarray(UV1, float)))


def _chain(cid="w1:1-2", length=600.0, hw=3.5, cls="G", oneway=False, surface="road_asphalt", roundabout=False):
    n = int(length / 0.5) + 1
    line = Polyline(np.column_stack([np.linspace(0.0, length, n), np.zeros(n)]))
    sec = SimpleNamespace(oneway=oneway, lanes=2, lanes_fwd=1, lanes_bwd=1, lane_w=3.25, edge_strip=0.25, cls=cls,
                          surface_mat=surface, provenance={"surface_override": True}, roundabout=roundabout)
    c = SimpleNamespace(
        id=cid, meta={}, roundabout=roundabout, t_a=0.0, t_b=0.0, length=float(line.length), line=line,
        bridge=np.zeros(n, bool), dirn=np.zeros(n, int),
        idx=lambda s: np.clip(np.rint(np.asarray(s) / 0.5).astype(int), 0, n - 1),
        hw_at=lambda s: np.full(np.shape(s), hw) if np.ndim(s) else hw,
        section=lambda s, secs: sec,
        crossfall_z=lambda s, lat: 100.0 - 0.02 * np.abs(np.asarray(lat, float)) + 0.0 * np.asarray(s, float),
    )
    return c, sec


def _run(chains):
    buf, cnt = _Buf(), {}
    DC.seal_cracks(buf, SimpleNamespace(chains=chains, sec_list=[]), cnt)
    return buf, cnt["seal_cracks"]


def test_stone_surfaces_have_their_own_sets():
    from roads.build_world import MATERIALS
    assert NW.SURFACE_MAT["sett"] == "road_sett"
    assert NW.SURFACE_MAT["cobblestone"] == NW.SURFACE_MAT["unhewn_cobblestone"] == "road_cobble"
    assert MATERIALS["road_sett"]["texture_set"] == MATERIALS["apron_sett"]["texture_set"] == "sett_granite"
    assert MATERIALS["road_cobble"]["texture_set"] == "cobble_fieldstone"
    # a carriageway material without a set falls back to the legacy procedural texture at a 1.6 m tile (the mosaic)
    for k, v in MATERIALS.items():
        if k.startswith("road_"):
            assert v.get("texture_set"), k


def test_stone_sets_are_element_scans_at_real_scale():
    spec = json.loads((REPO / "art-source/world/materials/materials_spec.json").read_text(encoding="utf-8"))["sets"]
    if "sett_granite" not in spec:
        pytest.skip("sets not built (cc0_fetch.py + build_all.py --only sett_granite,cobble_fieldstone)")
    for name, slots in (("sett_granite", {"road_sett", "apron_sett"}), ("cobble_fieldstone", {"road_cobble"})):
        e = spec[name]
        assert slots <= set(e["slots"])
        assert e["source"]["elements_per_tile"] > 50       # importer: element scans always get their real tile
        assert 1.8 <= e["tile_m"][0] <= 3.0
    # the scan has 26 setts across (counted): resulting pitch = tile / 26 within the 8/10 sett class incl. joint
    pitch = spec["sett_granite"]["tile_m"][0] / 26.0
    assert 0.078 <= pitch <= 0.105, pitch


def test_condition_states_and_shares():
    c, _ = _chain()
    vals = [DC.condition(SimpleNamespace(id=f"c{k}"), 10.0) for k in range(3000)]
    mults = sorted({m for _, m in DC.CONDITION_STATES})
    assert sorted(set(vals)) == mults
    for share, mult in DC.CONDITION_STATES:
        assert abs(vals.count(mult) / len(vals) - share) < 0.04
    # one state per CONDITION_LEN_M stretch
    assert DC.condition(c, 1.0) == DC.condition(c, DC.CONDITION_LEN_M - 1.0)


def test_seal_cracks_on_worn_asphalt_only_and_deterministic():
    c, _ = _chain(length=3000.0)
    buf, cnt = _run([c])
    buf2, cnt2 = _run([c])
    assert cnt == cnt2 and cnt["transverse"] > 5 and cnt["longitudinal"] > 3
    assert all(np.array_equal(a.V, b.V) for a, b in zip(buf.parts, buf2.parts))
    assert sum(len(p.T) for p in buf.parts) == cnt["tris"]
    for surface in ("road_asphalt_new", "road_sett", "road_cobble", "road_concrete", "road_gravel"):
        assert _run([_chain(surface=surface)[0]])[1]["tris"] == 0, surface
    assert _run([_chain(roundabout=True)[0]])[1]["tris"] == 0
    c_abs, _ = _chain()
    c_abs.meta["absorbed"] = True
    assert _run([c_abs])[1]["tris"] == 0


def test_seal_bands_lie_on_the_carriageway_under_the_paint():
    from roads import standards as S
    hw = 3.5
    c, _ = _chain(length=3000.0, hw=hw)
    buf, _ = _run([c])
    for p in buf.parts:
        assert p.layer == "markings" and p.mat == DC.SEAL_MAT
        assert (np.abs(p.V[:, 1]) <= hw + 1e-6).all(), p.src            # chain along +x: |N| = |lat| + half band
        z_surf = 100.0 - 0.02 * np.abs(p.V[:, 1])
        lift = p.V[:, 2] - z_surf
        assert (lift > DC.LIFT_PATCH - 2e-3).all() and (lift < S.MARKING_LIFT).all(), p.src
        assert (p.UV1[:, 0] < 0).all()                                    # negative length = short end fades
        assert set(np.round(p.UV1[:, 1], 2)) <= {2.6, 1.3}
        assert set(np.round(p.UV[:, 1], 6)) == {0.0, 1.0}
        w = np.hypot(*(p.V[: len(p.V) // 2, :2] - p.V[len(p.V) // 2:, :2]).T)
        assert w.max() <= DC.SEAL_W_M[1] + 1e-6 and w.min() >= DC.HAIRLINE_W_M - 1e-6


def test_cracks_meander():
    """A crack is never a ruler line: a transverse crack wanders along the road, a longitudinal one across it."""
    c, _ = _chain(length=3000.0)
    buf, _ = _run([c])
    tr = [p for p in buf.parts if p.src.startswith("seal:t:")]
    lo = [p for p in buf.parts if p.src.startswith("seal:l:")]
    assert tr and lo
    dev_t = [np.ptp(p.V[: len(p.V) // 2, 0]) for p in tr]      # station spread of a transverse crack
    dev_l = [np.ptp(p.V[: len(p.V) // 2, 1]) for p in lo]      # lateral spread of a longitudinal crack
    assert np.median(dev_t) > 0.08 and np.median(dev_l) > 0.05


def test_rates_scale_with_class_and_condition(monkeypatch):
    def tris(cls, cond):
        monkeypatch.setattr(DC, "condition", lambda c, s: cond)
        return _run([_chain(length=3000.0, cls=cls)[0]])[1]["tris"]
    assert tris("S", 1.0) < tris("G", 1.0)
    assert tris("G", 0.25) < tris("G", 1.0) < tris("G", 2.4)


def test_compact_plate_has_no_arm_axis_wheel_paths():
    """Critic 2.3: the plate of a compact roundabout must not carry the lane coordinate of the straight arm axes
    (parallel ruts under the splitter islands) - integer lane = no shader wheel paths, the edge data stays."""
    from roads import meshing as MS
    sec = SimpleNamespace(lane_edges=None, oneway=False, roundabout=False, edge_strip=0.0, lane_w=3.5)

    def chain(pts, hw=4.0):
        line = Polyline(pts)
        return SimpleNamespace(line=line, length=float(line.length), dirn=np.zeros(len(line.p), int),
                               idx=lambda s: int(np.argmin(np.abs(line.s - float(s)))), hw_at=lambda s: float(hw),
                               section=lambda s, sec_list: sec_list[0])

    cw = chain(np.column_stack([np.linspace(-40.0, -10.0, 61), np.zeros(61)]))
    arm = SimpleNamespace(chain=cw, end="b", s=lambda d: float(cw.length - d), direction=lambda d: np.array([-1.0, 0.0]))
    V = np.array([[-12.0, 1.2, 0.0], [-11.0, -2.6, 0.0], [-6.0, 0.9, 0.0], [0.0, 5.0, 0.0]])
    net = SimpleNamespace(sec_list=[sec])
    plain = MS._patch_uv1(net, SimpleNamespace(arms=[arm], trims={0: 2.0}), V, None)
    assert (np.abs(plain[:2, 0] - np.rint(plain[:2, 0])) > 0.05).any()        # ordinary plate: arm lanes
    comp = MS._patch_uv1(net, SimpleNamespace(arms=[arm], trims={0: 2.0}, compact=object()), V, None)
    assert np.allclose(comp[:, 0], 0.0)
    assert np.allclose(comp[:, 1], plain[:, 1])


def test_wheel_path_band_geometry():
    """Tracks of the compact roundabout: two bands a wheel gauge apart, draped, dropped off the carriageway."""
    Q = np.column_stack([np.linspace(0.0, 20.0, 41), np.zeros(41)])
    top = SimpleNamespace(z=lambda P, zref=None: np.where(np.asarray(P)[:, 0] < 15.0, 50.0, np.nan))
    buf = _Buf()
    n = DC._wp_band(buf, top, Q, 0.9, "t", None)
    p = buf.parts[0]
    assert n == len(p.T) and 0 < n < 2 * 40                 # the segments past x = 15 m (off the carriageway) are dropped
    assert p.V[p.T.ravel(), 0].max() < 15.0 + 1e-6
    assert np.allclose(p.V[p.T.ravel(), 2], 50.0 + DC.LIFT_WP)
    assert abs(np.ptp(p.V[:, 1]) - DC.WP_BAND_W_M) < 1e-6
    assert 2 * DC.WP_GAUGE_HALF_M - DC.WP_BAND_W_M > 0.5     # two separate paths, bare strip between them
    buf2 = _Buf()
    DC._wp_band(buf2, SimpleNamespace(z=lambda P, zref=None: np.full(len(P), 50.0)), Q, 0.7, "r", None, closed=True)
    u, length = buf2.parts[0].UV[:, 0], buf2.parts[0].UV1[0, 0]
    assert u.min() >= 2.5 and (length - u.max()) >= 4.0      # a loop never reaches the end fades of the material


