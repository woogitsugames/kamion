"""ADR 0207: authored place cameras from route stations + matching orthophoto crops for the top views.
uv run --project tools/worldgen python artifacts/dk65-tiles-0207/tools/cams.py <region> <spec.json>
spec: [{"id":..., "s":m, "kind":"top"|"drive"|"rev", "note":...}, ...]. Top: eye 150 m, fov 50 (=> 140 m x 249 m at
16:9, north up); drive/rev: eye 2.5 m (truck cab), fov 60, heading along / against the route. Ortho crop (same
footprint) -> artifacts/dk65-tiles-0207/<region>/ortho/top_<id>.jpg."""
import json, math, sys
from pathlib import Path
import numpy as np, rasterio, yaml
from rasterio.windows import from_bounds
from PIL import Image
ROOT = Path(__file__).resolve().parents[3]
reg, spec = sys.argv[1], json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))
R = ROOT / "Data/Regions" / reg
r = json.loads((R / "route_start.json").read_text(encoding="utf-8"))
o = yaml.safe_load((R / "region.yaml").read_text(encoding="utf-8"))["origin"]
P = np.asarray(r["points_en"], float); st = r["step_m"]
ds = rasterio.open(ROOT / json.loads((R / "ortho.json").read_text(encoding="utf-8"))["file"])
cams = []
for c in spec:
    i = min(int(round(c["s"] / st)), len(P) - 2)
    d = P[i + 1] - P[i]; hd = (math.degrees(math.atan2(d[0], d[1])) + 360) % 360
    e, n = P[i]
    if c["kind"] == "top":
        cams.append({"id": c["id"], "pos_en": [round(e, 1), round(n, 1)], "heading_deg": 0.0, "eye_m": 150, "fov_deg": 50,
                     "pitch_deg": -89.9, "note": f"QA top view (north up, 140 m x 249 m), route s = {c['s']} m: {c['note']}; pair = ortho/{c["id"]}.jpg"})
        x, y = e + o["x"], n + o["y"]
        a = ds.read(window=from_bounds(x - 124.5, y - 70, x + 124.5, y + 70, ds.transform), boundless=True)[:3].transpose(1, 2, 0)
        od = ROOT / "artifacts/dk65-tiles-0207" / reg / "ortho"; od.mkdir(parents=True, exist_ok=True)
        Image.fromarray(a).resize((960, 540), Image.LANCZOS).save(od / f"{c['id']}.jpg", quality=90)
    else:
        h = hd if c["kind"] == "drive" else (hd + 180) % 360
        cams.append({"id": c["id"], "pos_en": [round(e, 1), round(n, 1)], "heading_deg": round(h, 1), "eye_m": 2.5, "fov_deg": 60.0,
                     "pitch_deg": c.get("pitch", -1.5), "note": f"driver eye 2.5 m, {'along' if c['kind'] == 'drive' else 'against'} the route, route s = {c['s']} m: {c['note']}"})
out = {"schema": "truck-sim-pl/place-cameras/1",
       "provenance": f"authored_override (ADR 0207): control cameras of {reg} on the D64 route (DK65 variant A). Position region-local E/N (origin EPSG:2180 {o['x']:.0f}, {o['y']:.0f}), height = terrain (NMT) + eye_m, heading_deg compass, fov_deg vertical, pitch_deg up. Positions = route_start.json stations (right lane of travel); generated by artifacts/dk65-tiles-0207/tools/cams.py.",
       "cameras": cams}
(R / "control_cameras_place.authored.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(len(cams), "cameras")
